/*
 * Огонёк «Ниже рынка» — значок на фото карточки.
 *
 * Текстовый бейдж делил строку с ценой и читался как ещё одна метка. Огонь
 * понятен без слов («горячая цена»), а мерцание отличает его от статичных
 * значков и не даёт пройти мимо.
 *
 * Два языка пламени: внешнее красное качается медленнее, внутреннее
 * жёлтое — быстрее и в противофазе; за счёт разницы периодов рисунок не
 * повторяется в лоб. Задержка у каждой карточки своя (по её id), иначе
 * двадцать огоньков в ленте мигали бы хором, как гирлянда.
 */
function delayFor(id) {
  let h = 0
  for (let i = 0; i < String(id).length; i += 1) h = (h * 31 + String(id).charCodeAt(i)) >>> 0
  return -((h % 24) / 10)      // от 0 до -2,3 с: анимация стартует «с середины»
}

export default function Flame({ id, label }) {
  const d = `${delayFor(id)}s`
  return (
    <span className="flame-mark" role="img" aria-label={label} title={label} style={{ '--flame-delay': d }}>
      <span className="flame-halo" />
      <svg viewBox="0 0 24 24" width="22" height="22" aria-hidden="true">
        <path className="flame-outer" fill="#F0432A"
          d="M12.3 1.6c.6 3.3 4.4 5.4 5.8 9.4 1.3 3.7-.4 8-4.4 10.1a3.9 3.9 0 0 1-3.6 0C6.1 19 4.3 14.7 5.6 11c.7-2 1.9-3.1 2.8-4.4.9 1.4.8 2.7 1.1 3.5.9-1.8 2.1-4.3 2.1-6.6 0-.8.3-1.5.7-1.9z" />
        <path className="flame-mid" fill="#FF8F2B"
          d="M12 8.6c.7 2.2 3.4 3.7 3.9 6.7.4 2.6-1.4 5.3-3.9 5.6-2.5-.3-4.3-3-3.9-5.6.4-2.4 2.3-3.3 2.9-5.2.4-.7.7-1 1-1.5z" />
        <path className="flame-core" fill="#FFD84A"
          d="M12 13.4c.5 1.4 2 2.2 2 3.9 0 1.5-1 2.7-2 2.7s-2-1.2-2-2.7c0-1.7 1.5-2.5 2-3.9z" />
      </svg>
    </span>
  )
}
