/**
 * Плонк — валюта сайта — и его значок.
 *
 * Слово рядом с числом занимает место и требует склонения: «1 плонк»,
 * «2 плонка», «20 плонков», и всё это на трёх языках. Значок решает
 * обе беды разом: он короче любого слова и одинаков везде.
 *
 * Рисуем монету с той же буквой, что в знаке сайта, и с зелёным
 * уголком — чтобы её ни с чем не спутали. Вектор, а не картинка:
 * значок стоит и в заголовке баланса, и в мелкой подписи кнопки, и
 * везде должен быть чётким и одного цвета с текстом.
 */
export function PlonkIcon({ className = '' }) {
  return (
    <svg
      className={`plonk-icon ${className}`}
      viewBox="0 0 24 24"
      fill="none"
      aria-hidden="true"
    >
      {/* Квадратная рамка, а не круг. Кружок с буквой P читается как
          рубль в любом размере — это выяснилось, когда нарисовали
          рядом оба. Квадрат сразу уводит от монетной рифмы и повторяет
          знак сайта в шапке. */}
      <rect x="2.6" y="2.6" width="18.8" height="18.8" rx="5.4"
            fill="currentColor" opacity=".14" />
      <rect x="2.6" y="2.6" width="18.8" height="18.8" rx="5.4"
            stroke="currentColor" strokeWidth="1.7" />
      {/* Буква нарисована контуром, а не текстом: текст в значке
          зависит от шрифта, который может не загрузиться, и тогда
          значок поедет. */}
      <path
        d="M7.4 18.2V6.8h3.9c2.3 0 3.8 1.4 3.8 3.4s-1.5 3.5-3.8 3.5H9.6v4.5z
           m2.2-6.4h1.5c1.2 0 1.9-.6 1.9-1.5s-.7-1.5-1.9-1.5H9.6z"
        fill="currentColor"
        fillRule="evenodd"
      />
      {/* Квадратик — как на знаке сайта: он стоит выше буквы и прижат
          к верхнему правому углу, а не висит вровень с её плечом. Это
          и отличает наш знак от чужих. */}
      <rect x="14.9" y="4.5" width="4.4" height="4.4" rx="1.3" fill="currentColor" />
    </svg>
  )
}

/**
 * Число со значком. Везде, где раньше писали «37 плонков».
 */
export default function Plonk({ amount, className = '' }) {
  return (
    <span className={`plonk ${className}`}>
      {amount}
      <PlonkIcon />
    </span>
  )
}
