import { useState } from 'react'
import { CATEGORY_ICONS, FALLBACK_ICON } from './CategoryIcons'
import useDarkTheme from '../hooks/useDarkTheme'

/**
 * Картинка категории. Если файла нет или он не загрузился — показываем
 * контурную иконку: пустое место в плитке выглядит как поломка, а иконка
 * читается нормально.
 *
 * Все картинки приведены к общему квадрату 512×512 с равными полями, так
 * что подгонять масштаб и сдвиг под каждую категорию не нужно.
 */
export default function CategoryArt({ slug, parentSlug }) {
  // Пробуем по очереди: своя картинка, картинка родителя, контурная
  // иконка.
  //
  // Новые разделы заводятся без своей картинки, и плитка показывала
  // серый квадрат-заглушку: рядом с объёмными значками соседей это
  // выглядело поломкой. Увидел на записи экрана — «Корма» и
  // «Аквариумы» стояли пустыми квадратами среди нарядных плиток.
  //
  // Картинка родителя тут честнее любой случайной: подраздел и есть
  // часть своего раздела, «Аквариумы» с картинкой «Товаров для
  // животных» не соврут.
  const [step, setStep] = useState(0)

  // В тёмной теме — контурные значки вместо картинок.
  //
  // Картинки нарисованы на белом листе с тенью, и на тёмном фоне лист
  // виден светлым квадратом. Вырезать его нельзя: вместе с ним уходят
  // светлые части самих предметов. Подкладывать под картинку белое
  // тоже плохо — получается наклейка поверх карточки. А контурный
  // значок в тёмной теме выглядит ровно так, как и должен: линия
  // цветом текста на тёмном, без всякого фона. Значки те же, что уже
  // служат заменой, когда картинки нет.
  const dark = useDarkTheme()
  if (dark) {
    return CATEGORY_ICONS[slug] || CATEGORY_ICONS[parentSlug] || FALLBACK_ICON
  }

  const source = step === 0 ? slug : (step === 1 ? parentSlug : null)

  if (!source) {
    return CATEGORY_ICONS[slug] || CATEGORY_ICONS[parentSlug] || FALLBACK_ICON
  }

  return (
    <img
      className="cat-art"
      src={`/cat/${source}.png`}
      alt=""
      // Без ленивой загрузки: плитки разделов почти всегда в первом
      // экране, и откладывать их незачем — браузер начинал грузить
      // картинку позже, и раздел «доезжал» на глазах, плитка за
      // плиткой. Ленивость полезна для длинной ленты, а не для десятка
      // значков наверху.
      //
      // fetchpriority=high — просим браузер взять их раньше прочего:
      // это первое, что человек видит на странице раздела.
      // Именно fetchpriority строчными: эта версия React передаёт в
      // разметку как есть только известные ей свойства, а camelCase-имя
      // не узнаёт и ругается в консоли. Поймала проверка браузером.
      fetchpriority="high"
      decoding="async"
      onError={() => setStep((n) => n + 1)}
    />
  )
}
