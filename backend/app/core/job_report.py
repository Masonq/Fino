"""
Отчёт о ночных работах.

Конвейер, сводки, уборка, перевод — всё это работает само и молча.
Пока работает. Когда перестаёт, узнаёшь об этом случайно: через день
замечаешь, что новых объявлений нет, или человек жалуется, что не
получил письмо.

Поэтому каждая работа отчитывается: когда прошла, что сделала, а если
ничего — почему именно. «Ничего не отправлено» и «упало с ошибкой»
выглядят одинаково, если не написать причину, — а это совсем разные
вещи: в первом случае всё в порядке, во втором надо чинить.

Отчёты ложатся в тот же журнал действий, что и решения модераторов:
заводить вторую систему ради десяти записей в день незачем, а в
журнале у них уже есть и время, и поиск, и страница в админке.
"""
import logging

from app.core.audit import record
from app.core.database import SessionLocal

log = logging.getLogger(__name__)

ACTION = "job.report"


def report(name: str, *, done: int = 0, skipped: str | None = None,
           error: str | None = None, **numbers) -> None:
    """
    Записывает, чем кончилась работа.

    name    — короткое имя работы: «конвейер», «сводка продавцам».
    done    — сколько сделано: объявлений, писем, правок.
    skipped — почему ничего не сделано, если done равен нулю.
    error   — что сломалось, если сломалось.
    numbers — любые другие цифры работы, они попадут в подробности.

    Своя сессия базы: работы запускаются отдельными процессами, и та,
    что была у самой работы, к моменту отчёта уже закрыта.
    """
    try:
        with SessionLocal() as db:
            record(db, None, ACTION,
                   target_type="job", target_id=name,
                   reason=error or skipped,
                   done=done, error=bool(error), **numbers)
            db.commit()
    except Exception as exc:                            # noqa: BLE001
        # Отчёт не должен ронять саму работу: не записалось — и ладно,
        # работа важнее записи о ней.
        log.warning("отчёт о работе %s не записан: %s", name, exc)
