def to_nominative(text: str, words: int = 2, known_only: bool = False) -> str:
    """
    Приводит начало строки к именительному падежу.

    Сначала пробуем словарь: он знает часть речи и падеж, а потому не
    путает «вешалку» с «хочу». Если словаря нет — работает прежнее
    правило по окончаниям, оно грубее, но лучше, чем ничего.
    """
    by_dictionary = morph_nominative(text, words)
    if by_dictionary is not None:
        return by_dictionary
    return _to_nominative_by_endings(text, words, known_only)


def _to_nominative_by_endings(text: str, words: int = 2,
                              known_only: bool = False) -> str:
    """
    Переводит первые слова заголовка из винительного падежа в именительный.

    Трогаем только начало: дальше идут уточнения, где падеж уже верный,
    а слова вроде «камеру» встречаются и в них.
    """
    parts = text.split()
    if not parts:
        return text
    # прилагательное и существительное — не больше двух слов
    # Идём подряд с начала: «взрослую кошку» — два слова одной группы, и
    # править надо оба, иначе выходит «Взрослая кошку».
    for i in range(min(words, len(parts))):
        # Знак препинания прилипает к слову: «кошку,» не совпадало ни с
        # одним правилом, и падеж оставался винительным.
        raw = parts[i]
        word = raw.strip(" ,.;:!?—-«»\"'()")
        tail = raw[len(word) + raw.index(word):] if word and word in raw else ""
        lead = raw[:raw.index(word)] if word and word in raw else ""
        # Когда глагол не снимали, склоняем только то, что заведомо
        # является вещью: «картину» → «картина», а «почему» и «хочу»
        # остаются как есть — общее правило делало из них «почема».
        if known_only and not has_object_word(word):
            continue
        plural = _ACC_PLURAL.get(word.lower())
        if plural:
            fixed = plural if word.islower() else plural.capitalize()
            parts[i] = lead + fixed + tail
            continue
        if word.lower() in _INDECLINABLE or word.lower() in _VERB_FORMS:
            continue
        changed = False
        for pattern, ending in _ACC_ADJ:
            m = pattern.fullmatch(word)
            if m:
                parts[i] = lead + m.group(1) + ending + tail
                changed = True
                break
        if changed:
            continue
        m = _ACC_NOUN.fullmatch(word)
        if m:
            parts[i] = lead + m.group(1) + "а" + tail
            continue
        m = _ACC_NOUN_SOFT.fullmatch(word)
        if m:
            parts[i] = lead + m.group(1) + "я" + tail
    return " ".join(parts)
