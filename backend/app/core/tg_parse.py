# Слова, которые есть в каждом втором объявлении: по ним ничего не отличишь.
_COMMON_WORDS = frozenset("""
продам продаю продается продаётся отдам отдаю куплю новый новая новое новые
хорошем отличном идеальном прекрасном состоянии состояние самовывоз торг
уместен цена динар динара динаров евро размер размера белград beograd
можно есть пишите очень также более менее свой свои этот эта это все всё
доставка возможна почти практически года лет месяц срочно продажа
""".split())


# Одну и ту же марку пишут и латиницей, и кириллицей: «IKEA» и «Икеа»,
# «Samsung» и «Самсунг». Приводим к одному виду, иначе объявление о том же
# диване из соседнего чата выглядит другим товаром.
_TRANSLIT = str.maketrans({
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ж": "j",
    "з": "z", "и": "i", "й": "i", "к": "k", "л": "l", "м": "m", "н": "n",
    "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u", "ф": "f",
    "х": "h", "ц": "c", "ч": "c", "ш": "s", "щ": "s", "ъ": "", "ы": "i",
    "ь": "", "э": "e", "ю": "u", "я": "a",
})


def fingerprint(title: str | None, description: str | None) -> str:
    """
    Отпечаток смысла: основы значимых слов, по алфавиту.

    Одно и то же объявление кочует по чатам переписанным — «Продам диван
    IKEA, 25000 дин» и «Диван Икеа раскладной. 25 000 динар». По точному
    тексту их не сличить, а по набору основ видно, что товар один.

    Берём первые пять букв слова: окончания у переписанного текста
    другие, корень тот же.
    """
    text = f"{title or ''} {description or ''}".lower().replace("ё", "е")
    stems = set()
    for word in re.findall(r"[\w-]+", text):
        if word in _COMMON_WORDS:
            continue
        # Марка и модель — самое приметное в объявлении, а они короткие:
        # «m5», «16», «gb». Их берём от двух знаков, слова словами — от
        # четырёх, иначе отпечаток забьётся предлогами.
        marked = any(c.isdigit() for c in word) or word.isascii()
        if len(word) < (2 if marked else 4):
            continue
        stem = word if marked else word[:5]
        stems.add(stem.translate(_TRANSLIT))
    return " ".join(sorted(stems))[:500]


def same_thing(one: str | None, two: str | None) -> bool:
    """
    Об одном ли товаре два объявления.

    Мало общих слов — совпадение случайно: «платье» и «жилет» за одну цену
    сходятся на «женск» и «отличн». Поэтому требуем и долю совпадения, и
    общее приметное слово — марку, модель или число, которых у разных
    вещей не бывает.
    """
    first = set((one or "").split())
    second = set((two or "").split())
    if len(first) < 4 or len(second) < 4:
        return False
    common = first & second
    smaller = min(len(first), len(second))
    if len(common) * 10 < smaller * 6:
        return False
    # Общее приметное слово — марка, модель или число: у разных вещей их
    # не бывает. Либо совпадение почти полное — тогда это тот же текст,
    # просто переписанный.
    if any(w.isascii() or any(c.isdigit() for c in w) for w in common):
        return True
    return len(common) * 10 >= smaller * 8
