def clean_text(text: str) -> str:
    """
    Приводит сообщение к виду, годному для описания.

    В чатах к тексту прикладывают гроздь хэштегов для поиска внутри
    Telegram и ссылки на карты — у нас и то, и другое бесполезно: поиск
    свой, а ссылка в описании ведёт наружу. Заодно из-за хэштегов слова
    слипались с решёткой, и «#Vozdovac» не опознавался как район.
    """
    # ссылка вида [Bilećka](https://...) — оставляем подпись, адрес убираем
    text = _STRIKE_RE.sub(" ", text)
    text = _MD_LINK_RE.sub(r"\1", text)
    text = _URL_RE.sub("", text)
    # звёздочки и подчёркивания — разметка Telegram, у нас описание обычным
    # текстом, и «**Стол 3000 RSD**» показывалось со звёздочками
    text = _MD_MARK_RE.sub("", text)

    lines = []
    for raw in text.splitlines():
        line = raw.rstrip()
        # строка, существующая ради телефона, целиком не нужна
        if _CONTACT_LINE_RE.search(line) and _PHONE_RE.search(line):
            continue
        # то же и со строкой ради ника или почты
        if _CONTACT_BLOCK_RE.search(line):
            continue
        line = _PHONE_RE.sub("", line)
        line = _USERNAME_RE.sub("", line)
        # от строки остался один призыв — она была ради контакта
        if _CONTACT_LINE_RE.search(line) and len(line.strip(" ,.;:—-")) < 20:
            continue
        if _CALL_ONLY_RE.fullmatch(line.strip(" ,.;:—-!")):
            continue
        without_tags = _HASHTAG_RE.sub(" ", line)
        # строка из одних хэштегов не несёт ничего, кроме поиска в Telegram
        if line.strip() and not without_tags.strip():
            continue
        lines.append(re.sub(r"[ \t]+", " ", without_tags).strip())

    # схлопываем пустые строки, оставшиеся от вырезанного
    out, blank = [], False
    for line in lines:
        if not line:
            if blank or not out:
                continue
            blank = True
        else:
            blank = False
        out.append(line)
    return drop_link_invites("\n".join(out).strip())


def searchable_text(text: str) -> str:
    """
    Текст для распознавания города и категории.

    Отличается от описания тем, что хэштеги здесь не выбрасываются, а
    раскрываются в слова: «#Vozdovac #квартира» — часто единственное место,
    где названы район и предмет, и без них объявление теряет и то, и другое.
    """
    text = _STRIKE_RE.sub(" ", text)
    text = _MD_LINK_RE.sub(r"\1", text)
    text = _URL_RE.sub("", text)
    text = _MD_MARK_RE.sub(" ", text)
    return re.sub(r"#(?=[\w\u0400-\u04ff])", " ", text)


def _to_number(raw: str) -> float | None:
    """«1 200» и «1.200» — это тысяча двести, а не 1.2. Разделители убираем."""
    cleaned = re.sub(r"[ .,\u00a0]", "", raw)
    try:
        value = float(cleaned)
    except ValueError:
        return None
    # Отсекаем годы и телефоны: цена в 2016 почти всегда год выпуска
    if value < 3 or value > 5_000_000:
        return None
    return value


# «Новый в магазине стоит 25 000, цена: 17 000» — берём ту, что названа
# ценой, а не первую попавшуюся сумму.
_PRICE_LABELLED_RE = re.compile(
    r"(?:цена|price|cena)\s*[:\-—]?\s*"
    # «15. 000 RS» — точку от разделителя тысяч иногда отделяют пробелом
    r"(\d{1,3}(?:[ .,\u00a0]\s?\d{3})+|\d{2,7})\s*"
    r"(€|\$|(?:eur|евро|е|rsd|rds|рсд|rs|din\w*|дин\w*|usd)\b)?", re.I)


# Про какую сумму идёт речь, видно по словам перед ней.
# «Брал за 18000 рублей», «в магазине стоит 25 000» — это не наша цена.
_PAST_PRICE_RE = re.compile(
    r"(брал\w*|покупал\w*|купил\w*|куплен\w*|приобрел\w*|приобрёл\w*|стоит\w*|стоил\w*|"
    r"доставка|доставку|доставки|пересылк\w*|"
    r"в магазин\w*|новый стоит|отдавал\w*|платил\w*|"
    r"было|раньше|изначально|при покупке)", re.I)
# Разбор на запчасти и обмен: «Возможна замена. От 10 евро» — это цена
# детали или доплаты, а не вещи. Взяв её, мы показываем айфон за 10 €.
_PARTS_CONTEXT_RE = re.compile(
    r"(по\s+деталям|на\s+запчаст\w*|по\s+запчаст\w*|на\s+детал\w*|"
    r"возможна\s+замена|замена\s+(экрана|стекла|аккумулятора|батаре\w*)|"
    r"ремонт\w*\s+от|доставка\s+от|за\s+доставку|комисси\w*|"
    r"залог|задаток|предоплат\w*|аренда\s+от)", re.I)

# «Продаю за», «отдам за», «цена» — а вот это она
_SELL_PRICE_RE = re.compile(
    r"(цена|price|cena|прода[юмё]\w*|отда[юм]\w*|уступлю|заберите за)", re.I)
# Чужая валюта: рубли и прочее к нашим ценам отношения не имеют
_FOREIGN_RE = re.compile(r"(руб\w*|₽|грн|тенге|злот\w*)", re.I)

# «продаю за 7500» — цена названа, валюта опущена
# Строка списка, оканчивающаяся суммой: «- диван 25000», «1) Куртка 2000».
# Валюту в таких перечнях опускают почти всегда.
_LIST_PRICE_RE = re.compile(
    r"^\s*(?:[-–—•*]|\d{1,2}[.)])\s*[^\n]{3,60}?\s"
    r"(\d{1,3}(?:[ .,\u00a0]\d{3})+|\d{4,7})\s*$", re.M)

_SELL_BARE_RE = re.compile(
    r"(?:прода[юмё]\w*|отда[юм]\w*|уступлю|заберите)\s+за\s+"
    r"(\d{1,3}(?:[ .,\u00a0]\d{3})+|\d{2,7})"
    # Цифру после числа запрещаем: иначе разбор отступает на меньшее
    # число, и «100 евро» превращается в «10».
    r"(?!\d)"
    # Валюта названа — значит сумму разберёт правило выше, вместе с ней.
    # Без этой оговорки «отдам за 500 дин» уходило в евро.
    r"(?!\s*(?:%|м2|м²|гб|kg|кг|€|\$|[a-zа-яё]))", re.I)


# «1500-2000 дин», «от 1500 до 2000»: за сколько отдадут на самом деле,
# сказать нельзя, но ориентируется покупатель по нижней границе — она и
# стоит в фильтре «до N».
_RANGE_RE = re.compile(
    r"(?<![\w])(\d{2,7})\s*(?:-|—|–|до)\s*(\d{2,7})\s*"
    r"(€|\$|(?:eur|евро|evr[ao]|е|e|rsd|рсд|rs|din\w*|дин\w*|usd)\b)", re.I)


def _price_candidates(text: str) -> list[tuple[int, float, str | None]]:
    """Все суммы текста: позиция, значение, валюта."""
    out = []
    seen = set()
    for m in _PRICE_RE.finditer(text):
        value = _to_number(m.group(1))
        if value is not None:
            out.append((m.start(), value, CURRENCY_BY_WORD.get(m.group(2).lower())))
            seen.add(m.start())
    # Сумма с меткой «Цена», но без валюты: «Цена 3000» — тоже кандидат,
    # иначе в объявлении со строкой доставки побеждала цена доставки.
    for m in re.finditer(r"(?:цена|price|cena)\s*[:\-—]?\s*"
                         r"(\d{1,3}(?:[ .,\u00a0]\d{3})+|\d{2,7})(?!\d)", text, re.I):
        if m.start() in seen:
            continue
        value = _to_number(m.group(1))
        if value is not None:
            out.append((m.start(), value, None))
    return out


def _parts_only(text: str, pos: int) -> bool:
    """
    Сумма стоит в той части объявления, где говорят о запчастях или обмене.

    Смотрим весь текст до неё: «Продается целиком или по деталям» стоит
    абзацем выше, а «От 10 евро» — в самом конце, и по соседним словам
    связь между ними не видна.
    """
    return bool(_PARTS_CONTEXT_RE.search(text[:pos]))


def extract_price(text: str) -> tuple[float | None, str | None]:
    m = _RANGE_RE.search(text)
    if m:
        low, high = _to_number(m.group(1)), _to_number(m.group(2))
        if low is not None and high is not None and low < high:
            return low, CURRENCY_BY_WORD.get(m.group(3).lower())

    # Сначала разбираем суммы с валютой, глядя на слова перед каждой:
    # в объявлении их бывает несколько, и первая попавшаяся — часто та,
    # за которую вещь когда-то купили.
    candidates = _price_candidates(text)
    if len(candidates) > 1:
        scored = []
        for pos, value, currency in candidates:
            # Смотрим только ближайшие слова: окно пошире захватывало начало
            # фразы, и в «Покупал за 16000, продаю за 10000» обе суммы
            # выглядели как прошлая цена.
            before = text[max(0, pos - 40):pos]
            before = re.split(r"[.,;!?\n]", before)[-1] or before[-18:]
            after = text[pos:pos + 24]
            if _FOREIGN_RE.search(after) or _FOREIGN_RE.search(before[-12:]):
                continue          # цена в рублях — не наша
            if _PAST_PRICE_RE.search(before):
                continue          # столько отдали за неё раньше
            if _PARTS_CONTEXT_RE.search(before) or _PARTS_CONTEXT_RE.search(after):
                continue          # это цена детали или доплаты
            weight = 1 if _SELL_PRICE_RE.search(before) else 0
            scored.append((weight, -pos, value, currency))
        if scored:
            scored.sort(reverse=True)
            _, _, value, currency = scored[0]
            if currency is None:
                # Валюту не написали: до тысячи в Белграде торгуются в
                # евро, выше — в динарах.
                currency = "EUR" if value <= 1000 else "RSD"
            return value, currency

    # «Покупала за 16к, продаю за 7500» — валюту не написали вовсе. Само
    # число после «продаю за» — это цена, и терять её обиднее всего:
    # объявление уходит в ленту с пустым ценником.
    m = _SELL_BARE_RE.search(text)
    if m and not _PARTS_CONTEXT_RE.search(text[:m.start()]):
        value = _to_number(m.group(1))
        if value is not None:
            # До тысячи в Белграде торгуются в евро, выше — в динарах.
            return value, "EUR" if value <= 1000 else "RSD"

    # «Продам:\n- диван 25000\n- стол 3000» — валюту в списках не пишут
    # вовсе, а сумма стоит в конце строки. Берём только крупные числа:
    # мелкие чаще оказываются размером, объёмом или номером модели.
    m = _LIST_PRICE_RE.search(text)
    if m and not _PARTS_CONTEXT_RE.search(text[:m.start()]):
        value = _to_number(m.group(1))
        # Год выпуска стоит в конце строки так же, как цена: «Golf 5 2008».
        # Числа, похожие на год, пропускаем — ошибиться тут дороже.
        looks_like_year = value is not None and 1980 <= value <= 2035
        if value is not None and value >= 1000 and not looks_like_year:
            return value, "RSD"

    m = _PRICE_LABELLED_RE.search(text)
    if m:
        value = _to_number(m.group(1))
        if value is not None:
            currency = CURRENCY_BY_WORD.get((m.group(2) or "").lower())
            if currency:
                return value, currency
            # валюта не названа: до тысячи это почти наверняка евро
            if value <= 1000:
                return value, "EUR"

    m = _PRICE_K_RE.search(text)
    if m:
        value = _to_number(m.group(1))
        if value is not None:
            return value * 1000, CURRENCY_BY_WORD.get(
                m.group(2).lower(), "RSD" if m.group(2).lower().startswith(("d", "д")) else None)

    m = _PRICE_RE.search(text)
    if m:
        value = _to_number(m.group(1))
        # Единственная сумма в объявлении о разборе на детали — цена детали.
        # Пустая цена честнее: iPhone за 10 € в ленте выглядит обманом.
        if value is not None and not _parts_only(text, m.start()):
            return value, CURRENCY_BY_WORD.get(m.group(2).lower())
    m = _PRICE_AFTER_RE.search(text)
    if m:
        value = _to_number(m.group(1))
        if value is None:
            return None, None
        # Валюта не названа. До тысячи это почти наверняка евро: в динарах
        # такими суммами не оперируют. Выше — не угадываем: 10000 € и
        # 10000 динаров отличаются в сто раз, и промах в любую сторону
        # выглядит обманом. Цену не ставим, сумма остаётся в описании.
        return (value, "EUR") if value <= 1000 else (None, None)
    return None, None


def extract_city(text: str) -> str | None:
    """
    Город по упоминанию в тексте.

    Берём первое совпадение по длинному написанию: «Нови Сад» должен
    выигрывать у «Сад», иначе объявление уедет в другой город.
    """
    # Переводы строк и повторные пробелы схлопываем: город часто стоит
    # последней строкой, и с «\n» перед ним совпадение не находилось.
    low = " " + re.sub(r"\s+", " ", text.lower()) + " "
    best = None
    for alias, slug in CITY_ALIASES.items():
        if f" {alias} " in low or f" {alias}," in low or f" {alias}." in low:
            if best is None or len(alias) > best[0]:
                best = (len(alias), slug)
    return best[1] if best else None


_GREETING_RE = re.compile(
    r"^(всем\s+)?(привет\w*|здравствуйте|здравствуй|"
    # «Добрый день», «Доброго времени суток», а ещё «Добрый всем» и просто
    # «Добрый» — приветствие часто сокращают и переставляют слова.
    r"добр(ый|ое|ого)(\s+(день|вечер|утро|времени\s+суток|всем|дня))?|"
    r"доброе\s+утро|zdravo|pozdrav|dobar\s+dan)[\s,!.—-]*", re.I)


def strip_greeting(text: str) -> str:
    """
    Снимает приветствие в начале.

    «Всем привет. Меня зовут Кирилл, 19 лет...» — так пишут резюме в чатах,
    но заголовком это быть не может: в ленте у всех оказывается одно и то
    же «Всем привет», и объявления неразличимы.
    """
    out = _GREETING_RE.sub("", text.strip())
    # «Меня зовут X, 19 лет», «Мне 28 лет» — знакомство, а не суть
    # объявления. Снимаем в любом порядке: имя бывает и без возраста, и
    # возраст без имени.
    rest = out
    for _ in range(3):
        before = rest
        rest = re.sub(r"^меня\s+зовут\s+[\w-]+[\s,.—-]*", "", rest, flags=re.I)
        rest = re.sub(r"^мне\s+\d{1,2}\s*(?:лет|года?)[\s,.—-]*", "", rest, flags=re.I)
        rest = re.sub(r"^\d{1,2}\s*(?:лет|года?)[\s,.—-]*", "", rest, flags=re.I)
        if rest == before:
            break
    # Порог только чтобы не остаться с обрывком: «Мне 28 лет, ищу работу
    # барменом» давало 19 символов и откатывалось целиком.
    return (rest if len(rest) >= 8 else out).strip(" ,.;:—-")


def unshout(text: str) -> str:
    """
    Возвращает КАПС к обычному виду.

    Заглавными в чатах привлекают внимание, но в ленте такой заголовок
    кричит на остальные и читается хуже. Аббревиатуры и марки из двух-трёх
    букв (IKEA, LG, BMW) оставляем как есть.
    """
    letters = [c for c in text if c.isalpha()]
    if not letters:
        return text
    upper = sum(1 for c in letters if c.isupper())
    if upper / len(letters) < 0.7:
        return text
    words = []
    for word in text.split():
        core = "".join(c for c in word if c.isalpha())
        # Марку оставляем как написана: IKEA, LG, RTX. Короткие слова
        # кириллицей — это предлоги («НА», «ИЗ»), их опускаем в нижний.
        if core and core.isascii() and core.isupper() and len(core) <= 5:
            words.append(word)
            continue
        words.append(word.lower())
    out = " ".join(words)
    out = out[:1].upper() + out[1:]
    # Названиям районов и городов возвращаем заглавную букву: после
    # опускания регистра «НОВОМ НАСЕЛЬЕ» читалось как «новом населье».
    # Подменять слово целиком нельзя — в справочнике оно в именительном, а
    # в заголовке стоит в предложном: вышло бы «на Ново Насеље».
    return " ".join(
        w[:1].upper() + w[1:] if _is_place_word(w) else w
        for w in out.split()
    )


# Корни названий мест: по ним узнаём слово в любом падеже.
_PLACE_STEMS = frozenset(
    part[:5] for alias in list(DISTRICT_NAMES) + list(CITY_ALIASES)
    for part in alias.lower().split() if len(part) >= 5
)


def _is_place_word(word: str) -> bool:
    core = "".join(c for c in word if c.isalpha()).lower()
    return len(core) >= 5 and core[:5] in _PLACE_STEMS


# «В продаже ноутбук», «На продажу диван» — оборот, за которым идёт только
# родовое слово. Сам предмет назван ниже, моделью.
_INTRO_PHRASE_RE = re.compile(
    r"^(в\s+добрые\s+руки|в\s+хорошие\s+руки|бесплатно|даром|"
    # «Na prodaju:» — сербское «в продаже»
    r"na\s+prodaju\s*:?|prodaje\s+se|"
    r"в\s+продаже|на\s+продажу|срочная\s+продажа|продается|продаётся|"
    r"имеется|есть\s+в\s+наличии|отдам|отдаю)\s+", re.I)

# Модель: латиница с цифрой рядом — «HP Omen 16-xf0xxx», «RTX 4070»,
# «iPhone 11». Именно её ищут в ленте глазами.
_MODEL_LINE_RE = re.compile(r"[A-Za-z][A-Za-z&.\-]{1,}(?:\s+[A-Za-z0-9][\w.\-]*){0,4}")


def _looks_generic(title: str) -> bool:
    """
    Заголовок называет только род вещи: «Ноутбук», «Телефон», «Диван».

    Такой заголовок верен, но в ленте бесполезен: рядом стоят десятки
    ноутбуков, и выбирают по модели.
    """
    words = [w for w in title.split() if len(w) > 1]
    if len(words) > 2:
        return False
    return not any(c.isdigit() for c in title) and not _LATIN_IN_RE.search(title)


_LATIN_IN_RE = re.compile(r"[A-Za-z]{2,}")


def find_model(text: str, limit: int = 60) -> str | None:
    """
    Название модели из первых строк объявления.

    Автор часто пишет «В продаже ноутбук», а модель ставит следующей
    строкой — её и берём, иначе заголовок остаётся родовым.
    """
    for raw in text.splitlines()[:6]:
        line = _EMOJI_RE.sub("", raw).strip(" \t•·—-*#()")
        if not line or _SPEC_RE.match(line):
            continue
        m = _MODEL_LINE_RE.search(line)
        if not m:
            continue
        model = m.group(0).strip(" ,.;:-—")
        # Одно короткое слово латиницей — это не модель, а обрывок вроде
        # «Ram» из списка характеристик.
        if len(model) < 4 or " " not in model and not any(c.isdigit() for c in model):
            continue
        return model[:limit]
    return None


# Хвосты, которые продавец приписывает через запятую: цена, место,
# условия сделки. Всё это показывается отдельно, а в названии вещи только
# отнимает место — из-за них название обрезалось многоточием.
_TAIL_JUNK_RE = re.compile(
    r"^(самовывоз\w*|торг\w*|торг\s+уместен|доставка\w*|цена\s+\w+|"
    r"недорого|срочно|возможен\s+торг|обмен\w*|без\s+торга|"
    r"пишите\w*|звоните\w*|в\s+наличии|новое|новый|новая|б/?у|"
    # то же по-сербски: «срочно», «выгодно», «доставка», «возможен обмен»
    r"hitno|povoljno|dostava|moguca\s+zamena|moguća\s+zamena|"
    r"nov[ao]?|nekoriscen\w*|nekorišćen\w*|nikad\s+koriscen\w*|"
    r"nikad\s+korišćen\w*|ispravn\w*|kao\s+nov\w*)$", re.I)
# Хвост, состоящий только из суммы: «3000 дин», «250e». Голое число сюда
# не входит — «Туфли Mango, размер 37» теряло размер, а «iPhone 11, 128»
# объём памяти: без валюты понять, цена это или свойство вещи, нельзя.
_TAIL_PRICE_ONLY_RE = re.compile(
    r"^\d[\d\s.,\u00a0]*\s*(€|\$|eur|евро|evr[ao]|e|е|rsd|рсд|din\w*|дин\w*|usd)$",
    re.I)

# Голое число в хвосте: год выпуска или цена без валюты. Мелкие числа не
# трогаем — «размер 37» и «128» это свойство вещи, а не хвост.
_TAIL_BARE_NUMBER_RE = re.compile(r"^\d{4,7}$")

# Хвост с одной характеристикой: «200000 km», «72m2», «16 гб». Всё это
# показывается отдельными полями, а в названии вытесняет саму вещь.
# Память в названии техники не лишняя: «iPhone 11, 128gb» — так вещь и
# ищут. А пробег, площадь и вес показываются полями.
_TAIL_SPEC_RE = re.compile(
    r"^\d[\d\s.,\u00a0]*\s*"
    r"(км|km|kilometara|м2|м²|m2|kvadrata|см|cm|мл|ml|"
    r"кг|kg|л\b|вт|w)\.?$", re.I)


def _drop_place_tail(line: str) -> str:
    """
    Убирает из конца заголовка всё, что не про саму вещь.

    «Диван IKEA, 25000 динар, Земун, самовывоз» — вещь тут названа первым
    куском, остальное показывается отдельными полями. Режем только хвост
    и только по одному куску за раз: «Диван в Новом Саде» трогать нельзя,
    там место — часть фразы.
    """
    parts = [p.strip() for p in line.split(",")]
    while len(parts) > 1:
        tail = parts[-1]
        place = (len(tail.split()) <= 3
                 and (extract_city(tail) or extract_district(tail))
                 and not any(ch.isdigit() for ch in tail))
        if (place or _TAIL_JUNK_RE.match(tail)
                or _TAIL_PRICE_ONLY_RE.match(tail)
                or _TAIL_BARE_NUMBER_RE.match(tail)
                or _TAIL_SPEC_RE.match(tail)):
            parts.pop()
            continue
        break
    return ", ".join(parts).strip(" ,.;:-—") or line


def make_title(text: str, limit: int = 70) -> str | None:
    """
    Заголовок из первой содержательной строки.

    Отдельного заголовка в чатах нет, поэтому берём начало текста —
    так же, как его читает человек в ленте чата.
    """
    fallback = None
    seen_content = False
    for raw in text.splitlines():
        # Маркер перечня снимаем сразу, но помним о нём: у строки списка
        # число на конце — цена, а у обычной — объём памяти или модель.
        bare_raw = _EMOJI_RE.sub("", raw).strip(" \t")
        listed = bool(_LIST_NUMBER_RE.match(bare_raw))
        line = unshout(bare_raw.strip(" \t•·—-*#"))
        # Двоеточие на конце объявляет список: «Продаю пакетом:»,
        # «Характеристики:». Сам предмет назван пунктами ниже, а знак
        # снимается при дальнейшей чистке — смотрим строку целиком сейчас.
        if line.rstrip().endswith(":") and len(line.split()) <= 4:
            continue
        # «Всем привет!» и «Срочно!» как заголовок делают ленту неразличимой
        line = _SHOUT_RE.sub("", strip_greeting(line))
        # пропускаем строки из одних эмодзи, решёток и знаков
        if len(re.sub(r"[^\w]", "", line, flags=re.UNICODE)) < 8:
            continue
        line = re.sub(r"\s+", " ", line)
        # «Площадь: 72м2» — характеристика, а не название; заголовком берём
        # только если ничего лучше в тексте не нашлось
        if _SPEC_RE.match(line) and not _SPEC_NOT_RE.match(line):
            fallback = fallback or line
            continue
        # «В продаже только до 24 августа» — условие сделки, не предмет.
        # Проверяем начало строки, а не всю: «торг уместен» в хвосте — это
        # условие при названном предмете, и выбрасывать из-за него всё
        # объявление нельзя.
        if _SERVICE_LINE_RE.search(line[:40]):
            continue
        # Цена и в начале, и в конце заголовка лишняя: она стоит строкой
        # выше. В середине не трогаем — вырежется кусок фразы.
        line = _TITLE_PRICE_RE.sub("", line).strip(" ,.;:-—")
        line = _TITLE_PRICE_TAIL_RE.sub("", line).strip(" ,.;:-—")
        if not line:
            continue

        # Заголовок — это что продают, а не рассказ о вещи. «Велосипед. На
        # правом шатуне сорвана резьба...» — название здесь первое слово,
        # остальное относится к описанию.
        # Берём первое предложение, в котором есть что-то кроме восклицания:
        # «Срочно! Продаю растения по 2500 динар» начинается не с названия.
        # Берём первое предложение, которое называет предмет. Раньше брали
        # первое подходящее по длине — так в заголовок попадали «Меня зовут
        # Даниил» и «Мечтаете о цвете волос», после которых в том же посте
        # шло название вещи.
        chosen = None
        first_line = not seen_content
        seen_content = True
        # Делим строку словарём: своё правило рвало «1. вешалку» надвое,
        # а «3000 руб. Состояние» считало одним предложением.
        for part in split_sentences(line):
            candidate = _SHOUT_RE.sub("", part).strip(" .!?,;:-—")
            # Короткое слово годится, если это название вещи: «Стол»
            # после снятия цены — ровно четыре буквы.
            if len(candidate) < 4:
                continue
            if len(candidate) < 6 and not has_object_word(candidate):
                continue
            # Мягче судим только самое начало объявления: там автор
            # называет вещь, а дальше рассказывает о ней.
            if rejects_as_title(candidate, first_line=first_line and not chosen):
                continue
            chosen = candidate
            break
        if chosen is None:
            continue
        line = chosen
        # «Белград | Peugeot 308 | » — город и разделители в заголовке лишние:
        # город стоит отдельной строкой, а палки остаются от разметки поста
        parts = [p.strip() for p in re.split(r"\s*[|•]\s*", line) if p.strip()]
        if len(parts) > 1:
            meaningful = [p for p in parts if not extract_city(p) or len(p.split()) > 2]
            if meaningful:
                line = meaningful[0]
        # Точка-кружок и прочие разделители остаются от разметки поста и
        # висят в конце названия: «Medicube Mini Booster Pro ·»
        line = line.strip(" |•·—–-*~")

        # Пункт нумерованного списка: номер снимаем, а падеж правим так же,
        # как после глагола, — его задавал общий «Продам:» строкой выше.
        numbered = _LIST_NUMBER_RE.sub("", line)
        # Пункт списка стоит под общим «Продам:» — падеж задан им, и
        # выправить его надо так же, как после снятого глагола.
        from_list = listed or numbered != line
        if from_list:
            line = numbered.strip()

        # «в отличном состоянии» в хвосте вытесняет само название
        line = _CONDITION_TAIL_RE.sub("", line).strip(" ,.;:-—")
        line = _ADDRESS_TAIL_RE.sub("", line).strip(" ,.;:-—")
        line = _drop_place_tail(line)
        line = _BRACKET_TAIL_RE.sub("", line).strip(" ,.;:-—")
        line = _MATERIAL_TAIL_RE.sub("", line).strip(" ,.;:-—")
        if not line:
            continue

        # «Продаю женские вещи» — название здесь есть, лишний только глагол
        # Глагол и оборот идут парой: «Отдам в добрые руки взрослую кошку» —
        # сначала снимаем глагол, потом оборот, поэтому проходим дважды.
        without_verb = line
        for _ in range(2):
            cut = _INTRO_PHRASE_RE.sub("", without_verb).strip(" ,.;:-—")
            cut = _SELLING_VERB_RE.sub("", cut).strip(" ,.;:-—")
            if cut == without_verb:
                break
            without_verb = cut
        if not without_verb:
            continue
        if not without_verb:
            continue
        # Падеж правим только там, где сами сняли слово, задававшее его:
        # глагол продажи или номер пункта. Склонять что попало нельзя —
        # «Куплю гарнитуру» превращалось в «гарнитура», «Провожу занятия»
        # в «Провожа», «Живу и ищу работу» в «Жива».
        if without_verb != line or from_list:
            # Глагол сняли сами — падеж задавал он, правим и прилагательное,
            # и существительное.
            line = to_nominative(without_verb)
        else:
            # Глагола не было: строка могла начаться с пункта списка под
            # общим «Продам:». Правим только первое слово — дальше по строке
            # винительный падеж законный («Куплю гарнитуру Xbox»).
            line = to_nominative(without_verb, words=1, known_only=True)

        # «Продам вещи пакетом: футболки, джинсы» — слева от двоеточия
        # вводные слова, сам товар назван справа. Берём правую часть,
        # если левая коротка и предмета в ней нет.
        if ":" in line:
            left, right = line.split(":", 1)
            right = right.strip()
            if (len(left.split()) <= 3 and len(right) >= 6
                    and not has_object_word(left)):
                line = right

        # «Учебники по сербскому.Белград» — точку перед городом часто не
        # отделяют пробелом, и город прилипал к названию.
        glued = re.split(r"(?<=[а-яё])\.(?=[А-ЯЁ])", line)
        if len(glued) > 1 and len(glued[0]) >= 8:
            line = glued[0].strip()

        # Обрываем по первой запятой: до неё называют предмет, после —
        # состояние, город и условия, которым место в описании.
        head = line.split(",", 1)[0].strip()
        if 12 <= len(head) <= limit:
            line = head
        # Оценку состояния снимаем ещё раз: до обрезки по запятой она стояла
        # в середине строки, и правило для хвоста её не находило.
        line = _CONDITION_TAIL_RE.sub("", line).strip(" ,.;:-—")
        if not line:
            continue

        # Цену снимаем после обрезки: до неё «2500 динар каждое» стояло в
        # середине строки, и правило для хвоста его не находило.
        line = _TITLE_PRICE_WORD_RE.sub("", line)
        line = _TITLE_PRICE_TAIL_RE.sub("", line)
        line = _TITLE_PRICE_RE.sub("", line).strip(" ,.;:-—")
        if not line:
            continue

        # Заглавная — только если строку правили: после снятия приветствия
        # или глагола она начиналась со строчной. Нетронутое название не
        # трогаем, иначе «iPhone» становится «IPhone».
        # Заголовок начинается с заглавной всегда, кроме марок вроде
        # «iPhone»: там вторая буква заглавная, и трогать слово нельзя.
        head = line.split()[0] if line.split() else ""
        if line[:1].islower() and not head[1:2].isupper():
            line = line[0].upper() + line[1:]

        # «- диван 25000» — сумма в конце строки перечня: она уже стоит в
        # поле цены, в названии ей делать нечего.
        # Только у строк перечня: в обычном названии число на конце — это
        # объём памяти или модель, и убирать его нельзя («iPhone 11 128»).
        if from_list:
            line = re.sub(
                r"\s+(\d{1,3}(?:[ .,\u00a0]\d{3})+|\d{4,7})\s*$",
                lambda m: "" if not (1980 <= (_to_number(m.group(1)) or 0) <= 2035)
                else m.group(0), line).strip()

        # «Два брата-акробата 3» — тройка осталась от разметки поста.
        # «Коляска 3 в 1» под правило не подпадает: там число — часть
        # названия, и обрубок «3 в» читается как ошибка.
        if not re.search(r"\b\d+\s+в\s+\d+\s*$", line):
            line = strip_trailing_number(line)
        # Чистка могла отрезать как раз то слово, ради которого строка
        # прошла отбор, — проверяем итог, а не только кандидата.
        if rejects_as_title(line, first_line=first_line):
            continue

        # «Ноутбук» + «HP Omen 16-xf0xxx» строкой ниже = «Ноутбук HP Omen…»
        # «Добрый» после снятого приветствия — не название вещи, и
        # дописывать к нему модель нельзя: выходило «Добрый earpods 3».
        if _looks_generic(line) and not _GREETING_RE.match(line + " "):
            model = find_model(text)
            if model and model.lower() not in line.lower():
                line = f"{line} {model}"

        if len(line) <= limit:
            return line
        cut = line[:limit].rsplit(" ", 1)[0]
        return (cut or line[:limit]).rstrip(" ,.;:") + "…"
    return fallback if fallback and not rejects_as_title(fallback) else None


# Площадь пишут дробной («65.5 м2») и словом («72 квадрата», «kvadrata»),
# а иногда ставят слово впереди: «площадью 80».
_AREA_RE = re.compile(
    r"(?:(\d{2,4})(?:[.,]\d)?\s*(?:м2|м²|кв\.?\s*м|m2|m²|квадрат\w*|kvadrat\w*)"
    r"|(?:площад\w*|povrsin\w*|površin\w*)\D{0,4}(\d{2,4}))", re.I)
_ROOMS_WORD = {
    "однушк": 1, "гарсоньер": 1, "студи": 1,
    "двушк": 2, "двухкомнат": 2, "трешк": 3, "трёшк": 3, "трехкомнат": 3,
    "трёхкомнат": 3, "двухкомн": 2, "трёхкомн": 3, "трехкомн": 3,
    # Число словом пишут не реже, чем цифрой
    "однокомнат": 1, "однокомн": 1, "четырехкомн": 4, "четырёхкомн": 4,
    "пятикомнат": 5, "полуторка": 1, "полуторн": 1,
    # По-сербски число входит в само слово: «jednosoban», «trosoban»
    "jednosoban": 1, "jednosobn": 1, "garsonjer": 1,
    "dvosoban": 2, "dvosobn": 2, "dvoiposoban": 2,
    "trosoban": 3, "trosobn": 3, "cetvorosoban": 4, "četvorosoban": 4,
    "четырёхкомнат": 4, "четырехкомнат": 4,
}
_ROOMS_NUM_RE = re.compile(
    r"(\d)\s*[-.,]?\s*(?:комнат|комн\.?|соб[аыеу]|sob[aeni]|soban)", re.I)
_ROOMS_PLUS_RE = re.compile(r"гостин\w*\s*\+\s*(\d)\s*комнат", re.I)


def extract_rooms(text: str) -> int | None:
    """
    Число комнат. «Гостиная + 2 комнаты» — это трёшка: так считают в
    объявлениях, и покупатель ищет именно по этому числу.
    """
    low = text.lower()
    m = _ROOMS_PLUS_RE.search(low)
    if m:
        return int(m.group(1)) + 1
    for word, count in _ROOMS_WORD.items():
        if word in low:
            return count
    m = _ROOMS_NUM_RE.search(low)
    if m:
        n = int(m.group(1))
        return n if 1 <= n <= 9 else None
    return None


def extract_district(text: str) -> str | None:
    low = " " + re.sub(r"\s+", " ", text.lower()) + " "
    best = None
    for alias, name in DISTRICT_NAMES.items():
        if f" {alias} " in low or f" {alias}," in low or f" {alias}." in low or f" {alias}/" in low:
            if best is None or len(alias) > best[0]:
                best = (len(alias), name)
    return best[1] if best else None


def compose_title(category_slug: str | None, text: str) -> str | None:
    """
    Собирает заголовок из фактов, а не из первой строки.

    Для недвижимости строка из текста почти всегда бесполезна: люди
    начинают с хэштегов или с характеристик, и получалось «гостиная + 2
    комнаты». Комнаты, площадь и район — то, по чему квартиру и узнают.
    """
    if category_slug != "real-estate":
        return None

    rooms = extract_rooms(text)
    area = _AREA_RE.search(text)
    district = extract_district(text)

    if rooms:
        head = "Студия" if rooms == 1 and "студи" in text.lower() else f"{rooms}-комнатная квартира"
    elif area:
        head = "Квартира"
    else:
        return None

    parts = [head]
    if area:
        # У правила две ветви — число до слова и после; берём ту, что
        # сработала, иначе в заголовке оказывалось «None м²».
        parts.append(f"{next(g for g in area.groups() if g)} м²")
    if district:
        parts.append(district)
    return ", ".join(parts)


def title_from_facts(
    category_slug: str | None,
    sub_slug: str | None,
    text: str,
    attrs: dict | None = None,
) -> str | None:
    """
    Заголовок из того, что об объявлении известно наверняка.

    Нужен там, где автор о предмете не написал вовсе: рассказал о себе,
    задал вопрос читателю, начал с настроения. Такой заголовок сухой, зато
    в ленте по нему видно, что это кошка из Нови-Сада, а не «Дом — это
    место».
    """
    # У услуг предмет — это дело, а не раздел: «Услуги красоты» ничего не
    # говорит, «Стрижка и окрашивание волос» говорит всё.
    if category_slug in ("services", "beauty"):
        subject = service_subject(text)
        if subject:
            return subject

    # В резюме и вакансии предмет — профессия: по ней и ищут.
    if category_slug == "jobs":
        job = profession(text)
        if job:
            kind = "Резюме" if sub_slug == "resumes" else "Вакансия"
            return f"{kind}: {job.lower()}"

    subject = SUBJECT_BY_SUB.get(sub_slug or "")
    if not subject:
        subject = SUBJECT_BY_CATEGORY.get(category_slug or "")
    if not subject:
        return None

    parts = [subject]
    if attrs:
        for key in TITLE_ATTRS:
            if len(parts) >= 3:
                break
            value = attrs.get(key)
            if value in (None, "", []):
                continue
            label = ATTR_LABELS.get(key)
            parts.append(label.format(value) if label else str(value))

    district = extract_district(text)
    if district and len(parts) < 3:
        parts.append(district)
    return ", ".join(parts)


def build_title(
    category_slug: str | None,
    sub_slug: str | None,
    text: str,
    attrs: dict | None = None,
    fallback_title: str | None = None,
) -> str | None:
    """
    Единая точка: один заголовок по одному правилу для всех объявлений.

    Порядок жёсткий и одинаковый для любой категории: заголовок из фактов
    для недвижимости (там текст почти всегда начинается хэштегами), затем
    строка из текста, назвавшая предмет, и лишь потом — сборка из фактов.
    """
    # Живая строка лучше собранной, если она называет предмет: автор пишет
    # «Просторная трёхкомнатная квартира на Новом Населье», а сборка из
    # фактов даёт сухое «Квартира, 80 м²» и теряет всё остальное.
    if category_slug == "real-estate" and fallback_title:
        named = re.search(r"^(?!.*\bпосудомойк)(?=.*(кварти|дом|студи|"
                          r"комнат\w*\s+в|гараж|апартамент|таунхаус|"
                          r"помещени|stan\b|kuca))", fallback_title, re.I)
        if not named:
            fallback_title = None

    # Заголовок из текста уже прошёл отбор в make_title — судить его
    # заново строгой меркой нельзя: «Каланхоэ» и «Два брата-акробата»
    # отбраковывались повторно и объявление оставалось вовсе без названия.
    if fallback_title and not rejects_as_title(fallback_title, first_line=True):
        # Услуга с длинным описанием в заголовке обрезается многоточием и
        # читается хуже, чем короткое название дела.
        if fallback_title.endswith("…"):
            short = service_subject(text)
            if short:
                return short
        return fallback_title
    composed = compose_title(category_slug, text)
    if composed:
        return composed
    return title_from_facts(category_slug, sub_slug, text, attrs)


# Обороты рекламных постов: обращение к читателю и предложение услуг
# вообще, без конкретной вещи и цены.
_PITCH_MARKERS = (
    "вам нужна", "вам нужен", "вам необходим", "нужна надежная", "нужен надежный",
    "мы предлагаем", "мы оказываем", "наша компания", "наши услуги",
    "работаем без выходных", "звоните", "обращайтесь", "ждем ваших заявок",
    "ждём ваших заявок", "оставьте заявку", "гарантия качества",
    "быстро и качественно", "индивидуальный подход", "лучшие цены",
    "широкий выбор", "большой опыт работы", "профессиональная команда",
    # Пост салона про акцию: вещи в нём нет, есть повод прийти. У такого
    # объявления ни предмета, ни цены за него — только условия акции.
    "акция", "акцию", "скидка для новых", "только для новых клиентов",
    "успей записаться", "успейте записаться", "запишись", "запишитесь",
    "свободные окошки", "свободные окна", "осталось мест", "количество мест",
    "по промокоду", "первый сеанс", "пробное занятие бесплатно",
)


# Пометки, которыми закрывают объявление. Ставят и в самом сообщении
# (правкой), и ответом в ветке.
_SOLD_RE = re.compile(
    # Отрицание перед меткой меняет смысл на обратный: «ещё не продано»
    # значит, что вещь как раз в продаже. Без этой оговорки живые
    # объявления снимались с публикации.
    r"(^|[\s\[(*_])(?<!не )(?<!нет )(?<!ещё не )(?<!еще не )"
    r"(продано|продан|прода[нl]а|продал\w*|ушло|ушла|ушёл|забрали|забрано|"
    r"не\s*актуально|неактуально|снято с продажи|снят с продажи|закрыто|"
    r"prodato|prodata|prodat|nije aktuelno|rezervisano|"
    r"sold|reserved)([\s\])*_!.,]|$)", re.I)

# «не продано», «ещё в наличии» — вещь на месте, что бы ни стояло рядом.
_STILL_ON_SALE_RE = re.compile(
    r"((не|нет|ещё не|еще не)\s+(продано|продан\w*|ушло|забрал\w*)|"
    r"ещё\s+(актуально|в\s+наличии)|еще\s+актуально|"
    # «актуально» без отрицания перед ним: «не актуально» — ровно наоборот
    r"(?<!не )(?<!неактуально)\bактуально\b|"
    r"в\s+наличии|jos\s+aktuelno)", re.I)


def looks_sold(text: str) -> bool:
    """
    Объявление закрыто: вещь продали или сняли с продажи.

    Ищем пометку целым словом: «продано» внутри «непроданное» или в
    «продано будет завтра» — не то же самое, а вот «ПРОДАНО» отдельной
    строкой или в скобках у заголовка означает ровно это.
    """
    body = text or ""
    # Сначала смотрим, не сказано ли прямо, что вещь ещё продаётся:
    # «не продано», «ещё актуально» — метка рядом ничего не меняет.
    if _STILL_ON_SALE_RE.search(body):
        return False
    m = _SOLD_RE.search(body)
    if not m:
        return False
    # «продано будет только целиком» — не пометка, а часть фразы. Пометка
    # стоит особняком: в конце, в скобках или отдельной строкой.
    tail = (text[m.end():] or "").strip()
    if tail[:6].lower() in ("будет ", "тольк", "если ", "при "):
        return False
    return True


# Нижняя граница правдоподобия по категориям: ниже неё «цена» почти всегда
# оказывается чем-то другим — площадью, этажом, годом, весом посылки. Дом за
# 150 динар в ленте выглядит ошибкой, каковой и является.
# Порог привязан к подкатегории, а не к разделу: в «Транспорте» лежат и
# автомобили, и носки на колёса за тысячу динар, и общий порог отнимал у
# вторых цену.
PRICE_FLOOR: dict[str, tuple[float, float]] = {
    # подкатегория: (минимум в EUR, минимум в RSD)
    "flats": (50, 5000),
    "houses": (50, 5000),
    "commercial": (50, 5000),
    "cars": (100, 10000),
    "trucks": (100, 10000),
    "moto": (50, 5000),
}


def plausible_price(sub_slug: str | None,
                    price: float | None,
                    currency: str | None) -> bool:
    """
    Похоже ли это на настоящую цену для такой категории.

    Пустая цена честнее неправильной: по неверной покупатель приходит
    разочарованным, а продавца заваливают вопросами.
    """
    if price is None or not sub_slug:
        return True
    floor = PRICE_FLOOR.get(sub_slug)
    if not floor:
        return True
    eur_floor, rsd_floor = floor
    return price >= (rsd_floor if currency == "RSD" else eur_floor)


def looks_like_ad(text: str) -> bool:
    """
    Отличает рекламу услуги от объявления о продаже.

    Объявление говорит о конкретной вещи: что это, сколько стоит, где
    забрать. Реклама обращается к читателю и обещает качество: «Вам нужна
    надёжная доставка?» — здесь нет ни предмета, ни цены, и покупателю с
    такого объявления взять нечего.

    Судим по совокупности, а не по одному обороту: «звоните» в конце
    нормального объявления встречается сплошь и рядом.
    """
    low = text.lower()
    hits = sum(1 for marker in _PITCH_MARKERS if marker in low)
    if not hits:
        return False
    has_price, _ = extract_price(text)
    # два оборота и больше — реклама почти наверняка, даже с ценой
    if hits >= 2:
        return True
    # один оборот тянет на рекламу, только когда цены нет вовсе
    return has_price is None


# Слова, которые в объявлении встречаются и без всякого спама: «промокод
# на доставку», «ставки не принимаю», «акции компании». По одному такому
# слову объявление не выбрасываем — только если их несколько.
_WEAK_SPAM_MARKERS = (
    "промокод", "ставки", "акци", "крипт", "заработок", "инвестиц",
    "бонус", "кэшбэк", "кешбэк", "партнерская программа",
)


def looks_like_spam(text: str) -> bool:
    """
    Спам ли это.

    Фильтр удаляет объявление целиком, поэтому ошибка здесь дороже всего:
    вещь просто исчезает. Явные признаки срабатывают поодиночке, слабые —
    только вместе.
    """
    low = text.lower()
    if any(marker in low for marker in _SPAM_MARKERS):
        return True
    weak = sum(1 for marker in _WEAK_SPAM_MARKERS if marker in low)
    return weak >= 2


# Раз характеристика вынесена в поле, повторять её в описании незачем:
