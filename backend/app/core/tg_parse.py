# Приглашение уйти по ссылке. Саму ссылку мы вырезаем, и от фразы остаётся
# обрубок «...можно посмотреть тут:», который в описании выглядит поломкой.
_LINK_INVITE_RE = re.compile(
    r"(?:^|(?<=[.!?\n]))\s*[^.!?\n]{0,80}?"
    r"(?:другие\s+(?:вещи|товары|объявления)|остальны\w+|мои\s+объявлени\w+|"
    r"больше\s+фото|подробност\w+|весь\s+ассортимент|каталог|"
    r"смотрит[ье]|посмотреть|переходит[ье]|ссылка)"
    r"[^.!?\n]{0,60}[:—-]\s*$", re.I | re.M)


def drop_link_invites(text: str) -> str:
    """
    Снимает обрубки фраз, которые вели по вырезанной ссылке.

    «Другие вещи для продажи можно посмотреть тут:» без адреса — не
    информация, а недосказанное предложение, и заканчивать им описание
    нельзя.
    """
    out = _LINK_INVITE_RE.sub("", text)
    return re.sub(r"\n{3,}", "\n\n", out).strip(" \n:—-")


