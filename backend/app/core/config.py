from pathlib import Path

from pydantic_settings import BaseSettings

# Абсолютный путь до backend/.env — не зависит от того, откуда запущен
# процесс. Относительный ".env" читался только при запуске из backend/
# (так стартует systemd), а любой скрипт, запущенный из /opt/fino
# (deploy.sh, healthcheck.py), его не находил и тихо откатывался на
# захардкоженный дефолт с чужим паролем к базе.
ENV_FILE = Path(__file__).resolve().parent.parent.parent / ".env"


class Settings(BaseSettings):
    app_name: str = "PLONK"
    database_url: str = "postgresql://fino:fino@localhost:5432/fino"
    secret_key: str = "change-me-in-env"
    # Список через запятую в .env (CORS_ORIGINS=https://plonk.rs,https://www.plonk.rs).
    # Раньше было allow_origins=["*"] — открыто на любой сайт, до сегодняшнего
    # аудита оставалось как отметка «сузить перед продакшеном», которую
    # никто не убрал. Токен живёт в localStorage, не в куке (фронт нигде
    # не шлёт credentials: 'include'), так что чужой сайт всё равно не мог
    # бы использовать чужую сессию без отдельной XSS-дыры — но открытый
    # CORS всё равно даром отдаёт публичную выдачу (ленту, поиск) на
    # переиспользование чужими сайтами без всякого сдерживания.
    cors_origins: str = "https://plonk.rs,https://www.plonk.rs"
    default_languages: list[str] = ["ru", "en", "sr"]
    media_dir: str = "./media"
    # Проверка документов — сторонний сервис Didit, не своё хранилище:
    # документ и селфи снимаются и остаются у него, к нам они не
    # попадают вовсе. Пустые строки по умолчанию — раздел в профиле
    # сам скрывается, пока ключи не заданы (см. verification.py).
    didit_api_key: str = ""
    didit_workflow_id: str = ""
    didit_webhook_secret: str = ""
    # Повторная сверка лица у уже проверенного человека — модератор
    # запрашивает её, заподозрив продажу/передачу аккаунта. Отдельный,
    # более лёгкий workflow (только Liveness + Face Match, без пересъёмки
    # документа) — сверяет с биометрией, уже сохранённой у Didit с
    # первой проверки.
    didit_reverify_workflow_id: str = "a62e0209-df26-4931-be95-b1ec9b0b9329"

    # Платное продвижение объявлений — ЮKassa. Пустые строки по
    # умолчанию — покупка продвижения сама скрывается/отключается,
    # пока ключи не заданы, тем же приёмом, что и Didit выше.
    yookassa_shop_id: str = ""
    yookassa_secret_key: str = ""
    # Адрес самого сайта (фронтенда), не бэкенда — public_base_url
    # выше это адрес backend для файлов (с портом 8002), а сюда
    # браузер человека должен вернуться после проверки на Didit,
    # на страницу /profile, которую отдаёт фронтенд, а не бэкенд.
    site_base_url: str = "https://plonk.rs"

    # Web Push — ключи сгенерированы один раз для проекта, дефолт тут
    # только для локальной разработки без .env; на проде обязательно
    # переопределяются реальной парой (VAPID_PRIVATE_KEY/PUBLIC_KEY).
    # Публичный уходит на фронт как есть, приватным подписывается
    # каждое отправленное уведомление — если он утечёт, кто угодно
    # сможет слать пуши от имени сайта всем подписанным браузерам.
    vapid_private_key: str = ""
    vapid_public_key: str = ""
    # VAPID требует контакт в заголовке — на случай, если браузер или
    # оператор пуш-сервиса захочет пожаловаться на злоупотребление.
    vapid_subject: str = "mailto:admin@plonk.rs"

    # Почта для кодов подтверждения (пока не задана — коды пишутся в журнал)
    smtp_host: str | None = None
    smtp_port: int = 587
    smtp_user: str | None = None
    smtp_password: str | None = None
    # Отправитель. Не «noreply»: письмо от адреса, на который нельзя
    # ответить, почтовые службы считают рассылкой, а человек — чем-то
    # безличным. На «привет» ответить можно, и это видно сразу.
    smtp_from: str = "PLONK <account@plonk.rs>"
    # Ключ Resend: с ним письма уходят через него, без него — по SMTP.
    # Обычной почтой с нашего сервера они попадают в спам почти всегда.
    resend_api_key: str | None = None
    # Куда человек может ответить на письмо. Тот же адрес, что и у
    # отправителя: разные адреса в письме выглядят подозрительно, а
    # человеку всё равно, лишь бы ответ дошёл.
    support_email: str = "account@plonk.rs"

    # Запасная отправка через Gmail — для тех, кому иначе не доходит.
    #
    # Apple отклоняет наши письма целиком: 554 5.7.1 [HM07] и [HM08],
    # «rejected due to local policy». Проверено, что дело не в
    # содержимом — отказ пришёл и на письмо из шести цифр простым
    # текстом, — и не в подписях: SPF, DKIM и DMARC на месте. Значит
    # Apple просто не доверяет молодому домену без истории отправок, а
    # набирается она месяцами.
    #
    # Письмам с серверов Google Apple доверяет: репутация у них
    # накоплена годами. Поэтому на ящики iCloud отправляем через Gmail,
    # остальным — как прежде.
    #
    # Пароль здесь — не пароль от почты, а «пароль приложения»
    # (myaccount.google.com/apppasswords), 16 символов. Обычный пароль
    # Google для сторонних программ давно не принимает.
    gmail_user: str | None = None
    gmail_app_password: str | None = None

    # Telegram-бот для кодов и уведомлений
    telegram_bot_token: str | None = None
    # Имя бота для кнопки «Войти через Telegram»: человек нажимает и
    # попадает к нему, а бот присылает ссылку для входа.
    telegram_bot_username: str = "Baraholka_plonk_bot"
    # Где лежат снимки. Отдельно от адреса сайта: страницы открываются
    # по одному адресу, а картинки отдаёт само приложение по другому —
    # и снимки, сохранённые с адресом сайта, просто не находятся.
    media_base_url: str | None = None

    # свой сервер перевода — без ограничений по количеству запросов
    translate_url: str | None = None

    # Нейросеть для заголовков там, где правила не справились. Ключ
    # бесплатный, берётся в Google AI Studio; без ключа парсер работает
    # как прежде, только на правилах.
    gemini_api_key: str | None = None
    gemini_model: str = "gemini-3.5-flash-lite"
    # Запасные провайдеры. Лимиты у всех считаются отдельно, поэтому
    # несколько ключей складываются в общий запас: кончился один — работа
    # продолжается на следующем, а не встаёт до полуночи.
    groq_api_key: str | None = None
    # На новых ключах Llama больше не выдают; gpt-oss-120b для
    # разбора объявлений подходит даже лучше.
    groq_model: str = "openai/gpt-oss-120b"
    # Mistral: месячный запас большой, но не больше двух запросов в минуту —
    # для фоновой работы это подходит, для живого ответа нет.
    mistral_api_key: str | None = None
    mistral_model: str = "mistral-small-latest"
    # OpenRouter: один ключ к десяткам моделей, полсотни запросов в сутки.
    openrouter_api_key: str | None = None
    # Маршрутизатор бесплатных моделей, а не одна конкретная.
    #
    # Мы указывали llama-3.3-70b-instruct:free — и в один день она стала
    # платной: перевод и переписывание заголовков встали с ответом 404
    # «модель недоступна бесплатно». Бесплатный список у провайдера
    # меняется без предупреждения, и привязываться к одной модели значит
    # ломаться при каждой такой перестановке.
    #
    # openrouter/free сам выбирает доступную на сейчас. Качество чуть
    # плавает, но для перевода заголовков и коротких описаний это не
    # важно, а работать оно будет всегда.
    openrouter_model: str = "openrouter/free"
    # Сколько объявлений за один заход отдаём модели: бесплатный тариф
    # ограничен по суткам, и тратить его весь на один прогон незачем.
    ai_titles_per_run: int = 120

    # Чтение барахолок в Telegram. Ключи с my.telegram.org, телефон — того
    # аккаунта, который состоит в этих чатах. Сессия лежит рядом файлом,
    # так что код подтверждения запрашивается только при первом входе.
    tg_api_id: int | None = None
    tg_api_hash: str | None = None
    tg_phone: str | None = None
    tg_session: str = "tg.session"

    # Адрес, по которому сайт забирает файлы. Загрузки с сайта записывают
    # полный адрес, потому что фронтенд и бэкенд отвечают на разных портах,
    # и относительный «/media/...» ушёл бы не туда. Импорту брать этот
    # адрес неоткуда — задаём здесь.
    public_base_url: str = "http://89.208.113.147:8002"

    class Config:
        env_file = ENV_FILE


settings = Settings()
