# Тема чата → наша категория. Заполняется под каждый чат: у них разные
# наборы тем, и одинаковых названий почти нет.
TOPIC_MAP: dict[str, str] = {}

_WORD_RE = re.compile(r"[a-zа-яё0-9]+", re.I)


def _fold(text: str) -> str:
    """Приводит текст к общему виду: строчные, без диакритики и лишних знаков."""
    text = unicodedata.normalize("NFD", text.lower())
    text = "".join(c for c in text if unicodedata.category(c) != "Mn")
    return " " + " ".join(_WORD_RE.findall(text)) + " "


def _matches(word: str, folded: str) -> bool:
    """
    Ключевое слово должно начинать слово в тексте, а не сидеть в середине.

    Подстрока где угодно давала дикие промахи: «шин» находилось в «машин»,
    и прокат машин уезжал в «Шины и диски». Ключевые слова у нас — корни,
    поэтому сравниваем по началу слова, а окончание остаётся любым.
    """
    needle = _fold(word).strip()
    if not needle:
        return False
    # Слово из нескольких частей («ищу работу») ищем как есть.
    if " " in needle:
        return f" {needle}" in folded
    # Корень, записанный с пробелом на конце («кот »), — это слово целиком:
    # иначе он ловит «которая», «котлета», «который», и объявление об
    # одежде уезжало в «Кошек».
    # Пробел ставит сам _fold, поэтому смотрим на исходную запись корня.
    if word.endswith(" "):
        return f" {needle} " in folded
    return f" {needle}" in folded


