def classify_sub2(parent_sub_slug: str, text: str) -> str | None:
    """
    Третий уровень — то же правило, что у classify_sub(), только проще:
    без обучаемой модели (для третьего уровня её ещё не размечали) и без
    электроники-специфичных разборов вроде «что раньше в заголовке» —
    там, где они нужны, это уже решено на втором уровне до вызова этой
    функции. Ничья, как и на втором уровне, означает «не уверены» —
    объявление остаётся на уровне выше, а не гадает.
    """
    table = SUB2_KEYWORDS.get(parent_sub_slug)
    if not table:
        return None
    folded = _fold(text)
    head = _fold(text[:80])
    scores = {}
    for slug, words in table.items():
        hit = sum((min(len(w.split()[-1]), 8) + (2 if " " in w else 0))
                  * (4 if _matches(w, head) else 1)
                  for w in words if _matches(w, folded))
        if hit:
            scores[slug] = hit
    if not scores:
        return None
    best = max(scores, key=lambda s: scores[s])
    if list(scores.values()).count(scores[best]) > 1:
        return None
    return best
