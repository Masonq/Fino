def classify_sub(parent_slug: str, text: str) -> str | None:
    """
    Подкатегория внутри уже определённой категории.

    Возвращает None, если уверенности нет: объявление останется в
    родительской категории. Это не потеря — родитель показывает всё
    вложенное, — а вот ноутбук в «Телефонах» пришлось бы искать руками.
    """
    table = SUB_KEYWORDS.get(parent_slug)
    if not table:
        return None
    # «Карман для телефона», «Отделение для ноутбука» — сумка перечисляет
    # свои отделения, а не является телефоном или ноутбуком. Та же
    # болезнь, что у «для настройки/ремонта» на уровне разделов
    # (см. _TOOL_PURPOSE_RE в classify()) — только там, а не в
    # classify_sub, поэтому рюкзаки с карманом под телефон уезжали
    # в «Телефоны».
    if parent_slug == "electronics":
        text = _DEVICE_POCKET_RE.sub(" ", text)
    # «Баскетбольное кольцо», «кольцо диафрагмы» — то же слово, что у
    # ювелирного кольца, настоящие омонимы, а не ошибка сопоставления
    # по началу слова. «Кольцо» вообще слишком общее — обруч у мяча,
    # деталь объектива, что угодно круглое.
    if parent_slug == "fashion":
        text = re.sub(r"баскетбольн\w*\s+кольц\w*", " баскетбольный обруч ", text, flags=re.I)
        text = re.sub(r"кольц\w*\s+диафрагм\w*", " деталь объектива ", text, flags=re.I)
    # «Женская обувь» — это обувь: пол уточняет вещь, но не заменяет её
    # вид, поэтому разделы по полу весят меньше предметных.
    softer = {"women", "men"}
    folded = _fold(text)
    # Раздел задаёт начало объявления: там названа сама вещь. Гараж и
    # паркинг в описании квартиры — удобства, а не предмет продажи, и
    # перевешивать они не должны.
    head = _fold(text[:80])
    scores = {}
    for slug, words in table.items():
        # Считаем длину совпавших слов, а не их количество: «квартиру» и
        # «комнат» в одном объявлении давали ничью и оставляли его без
        # раздела, хотя длинное слово тут явно точнее.
        # Вес по длине корня, а не всей фразы: «сдам гараж» иначе тянет
        # сильнее «квартир», и квартира с подземным паркингом уезжала в
        # раздел гаражей. Фраза из двух слов точнее одиночного корня, но
        # ненамного — надбавка небольшая и с потолком.
        hit = sum((min(len(w.split()[-1]), 8) + (2 if " " in w else 0))
                  * (4 if _matches(w, head) else 1)
                  for w in words if _matches(w, folded))
        if slug in softer:
            hit = hit // 2
        if hit:
            scores[slug] = hit
    if not scores:
        return None
    # Названо жильё — значит продают его, а гараж и паркинг при нём
    # удобства: «квартира 48 м², гараж в подземном паркинге» — это
    # квартира. Обратное неверно: у гаража квартиры не бывает.
    if parent_slug == "real-estate" and "garages" in scores:
        if any(k in scores for k in ("flats", "houses", "rooms")):
            scores.pop("garages")

    # «Русская клавиатура» у макбука в описании, «чехольчик» третьим
    # пунктом после iPad+pencil, «Чехол для iPhone» первым словом — во
    # всех трёх есть и модель устройства, и слово аксессуара, а разница
    # в том, что названо раньше в заголовке. Первое слово — это то, что
    # продают, остальное — довесок. По очкам решать нельзя: у «чехол»
    # корень длиннее, чем «ipad», и он выигрывал спор всегда, даже когда
    # сам был довеском.
    if parent_slug == "electronics" and "gadgets" in scores:
        title_only = _fold(text.split("\n", 1)[0])

        def _pos(word: str) -> int | None:
            needle = _fold(word).strip()
            if not needle:
                return None
            probe = f" {needle} " if word.endswith(" ") else f" {needle}"
            idx = title_only.find(probe)
            return idx if idx >= 0 else None

        def _first_pos(words: list[str]) -> int | None:
            found = [p for p in (_pos(w) for w in words) if p is not None]
            return min(found) if found else None

        gadgets_pos = _first_pos(table.get("gadgets", []))
        device_positions = {
            k: _first_pos(table.get(k, []))
            for k in ("laptops", "computers", "tablets", "phones")
            if k in scores
        }
        device_positions = {k: p for k, p in device_positions.items() if p is not None}

        if gadgets_pos is None:
            # Слово-аксессуар есть только в описании (макбук + русская
            # клавиатура) — устройство названо в заголовке, значит оно и
            # есть товар.
            if device_positions:
                scores.pop("gadgets")
        elif device_positions:
            earliest_device = min(device_positions.values())
            if gadgets_pos < earliest_device:
                # Аксессуар назван раньше устройства — он и есть товар
                # («Чехол для iPhone»).
                return "gadgets"
            # Устройство названо раньше — аксессуар был довеском
            # («iPad + pencil + чехольчик»).
            scores.pop("gadgets")

    if not scores:
        return None
    best = max(scores, key=lambda s: scores[s])
    # ничья означает, что текст подходит двум разделам сразу — не угадываем
    if list(scores.values()).count(scores[best]) > 1:
        return None
    return best
