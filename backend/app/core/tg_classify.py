def classify(text: str) -> tuple[str | None, int]:
    """
    Возвращает наиболее подходящую категорию и число совпавших признаков.

    Число нужно не для красоты: одно случайное слово («стол» в объявлении о
    квартире) не должно перевешивать тему чата, поэтому решение принимается
    с оглядкой на то, насколько уверенно сработал разбор.
    """
    # Начало объявления весит больше хвоста: предмет называют первой
    # строкой, а «доставка по Белграду» в конце есть у половины постов — из-за
    # неё куртки уезжали в «Перевозки».
    # Техника названа — это товар, если рядом не сказано, что с ней
    # работают: «Чиню стиральные машины» и «Ремонт бойлеров» — услуги.
    if (_APPLIANCE_RE.search(text)
            and not _SERVICE_WORK_RE.search(text)
            and not _SERVICE_ACTION_RE.search(text)):
        return "home-garden", 3
    if _SERVICE_WANTED_RE.search(text):
        return "services", 2
    if _JOB_SEEKER_RE.search(text):
        return "jobs", 3
    if _RENTAL_RE.search(text) or _SERVICE_ACTION_RE.search(text):
        return "services", 2
    # Работа названа, а глагола продажи нет — это услуга, даже если в тексте
    # полно названий техники: у мастера по бойлерам их всегда много.
    if _SERVICE_WORK_RE.search(text) and not _SELLING_RE.search(text):
        return "services", 3
    # Обученная модель судит по всему тексту сразу, а не по одному
    # совпавшему слову, и потому не путает «трек гараж Hot-Wheels» с
    # гаражом на продажу. Правила выше неё — это случаи, где мы уверены
    # наверняка; словари ниже — страховка, когда модель сомневается.
    guessed, margin = model_predict(text)
    if guessed and margin >= MIN_MARGIN:
        return guessed, 3

    folded = _fold(text)
    head = _fold(text[:120])
    if _HOUSEHOLD_MACHINE_RE.search(text):
        # Слово «машина» тут про технику, а не про автомобиль. Убираем его
        # из разбора, но подставляем признак дома — иначе объявление
        # остаётся вовсе без опознания.
        folded = re.sub(r"машин\w*", " бытоваятехника ", folded)
        head = re.sub(r"машин\w*", " бытоваятехника ", head)
    scores: dict[str, int] = {}
    for slug, words in KEYWORDS.items():
        hit = sum(2 if _matches(w, head) else 1
                  for w in words if _matches(w, folded))
        if hit:
            scores[slug] = hit
    if not scores:
        return None, 0
    best = max(scores, key=lambda s: scores[s])
    return best, scores[best]


def explain(text: str) -> dict[str, list[str]]:
    """
    Какие слова сработали в каждой категории.

    Нужна для сухого прогона: по одному только итогу («обувь уехала в
    Украшения») причину не найти, а список совпавших слов показывает её
    сразу.
    """
    folded = _fold(text)
    out: dict[str, list[str]] = {}
    for slug, words in KEYWORDS.items():
        hits = [w for w in words if _matches(w, folded)]
        if hits:
            out[slug] = hits
    for parent, table in SUB_KEYWORDS.items():
        for slug, words in table.items():
            hits = [w for w in words if _matches(w, folded)]
            if hits:
                out[f"{parent}/{slug}"] = hits
    return out


def decide_for(expected: str | None, text: str) -> tuple[str | None, bool]:
    """
    То же решение, но категория из темы уже известна по номеру.

    Возвращает (категория, публиковать ли сразу). Сразу — только когда тема
    и текст сходятся: расхождение чаще всего значит, что человек написал не
    в тот раздел, и разобрать это должен человек, а не догадка.
    """
    guessed, score = classify(text)

    if expected and guessed:
        return (expected, True) if expected == guessed else (guessed, False)
    if expected:
        # текст ни на что не похож — доверяем теме, но показываем человеку
        return expected, False
    if guessed and score >= 2:
        return guessed, True
    return guessed, False


def decide(topic: str | None, text: str) -> tuple[str | None, bool]:
    """
    Итог: (категория, публиковать ли сразу).

    Сразу публикуем, только когда тема чата и разбор текста сходятся. Всё
    остальное — на модерацию: лучше очередь, которую разберёт человек, чем
    объявление о квартире в разделе мебели.
    """
    expected = TOPIC_MAP.get((topic or "").strip().lower())
    guessed, score = classify(text)

    if expected and guessed and expected == guessed:
        return expected, True
    if expected and not guessed:
        # текст ни на что не похож — доверяем теме, но показываем человеку
        return expected, False
    if guessed and score >= 2 and not expected:
        # темы нет (обычный чат без разделов), но текст говорит уверенно.
        # Порог в два признака: одного мало — слово «стол» попадается и в
        # объявлении о квартире, — а три отправляли на модерацию половину
        # коротких и совершенно понятных объявлений.
        return guessed, True
    return guessed or expected, False


