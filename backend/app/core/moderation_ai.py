"""
Проверка объявлений перед лентой.

Тысяча триста объявлений на проверке — руками не пересмотреть, а
одобрять вслепую нельзя: среди перенесённых из чатов попадаются
лекарства, документы и мошенничество, и отвечать за это будет сайт.

Порядок такой же, как с заголовками: сначала правила, потом нейросеть
для подозрительного. Правила ловят явное — «продам права», «нужна
предоплата» — мгновенно и бесплатно. Остальное смотрит модель.

Спорное не одобряем и не отклоняем: оставляем человеку. Ошибка в обе
стороны дорога — пропущенное мошенничество бьёт по сайту, а
отклонённое честное объявление отваживает продавца.
"""
import json
import logging
import re

log = logging.getLogger(__name__)

# Прямо запрещённое: продажа таких вещей незаконна в Сербии, и разбирать
# их нейросетью незачем — правила надёжнее и быстрее.
FORBIDDEN = re.compile(
    r"(?:^|\W)("
    # Оружие
    r"пистолет|автомат\s+калашн|винтовк|патрон\w*\s+к\b|глушител|"
    r"травматик|нарезн\w+\s+оруж|"
    # Лекарства по рецепту и запрещённое
    r"трамадол|прегабалин|лирик\w*\s+капсул|феназепам|алпразолам|"
    r"анаболик|тестостерон\s+ампул|соматропин|"
    # Документы
    r"водительск\w+\s+удостоверен\w+\s+куп|"
    r"диплом\s+куп|паспорт\s+куп|прописк\w+\s+куп|"
    r"боравак\s+куп|вид\s+на\s+жительство\s+куп|"
    # Живые люди и органы
    r"сурогатн|донор\s+орган|"
    # Явное мошенничество
    r"обнал\w*|отмыв\w+\s+денег|дроп\w+\s+карт|"
    r"взлом\s+аккаунт|накрутк\w+\s+подписчик"
    r")", re.I)

# Просят денег вперёд — самый частый обман в барахолках.
PREPAY = re.compile(
    r"(предоплат\w+\s+(?:100|полн)|только\s+предоплат|"
    r"переве[сд]\w+\s+сначала|сначала\s+оплат\w+\s+потом)", re.I)


def by_rules(title: str, body: str) -> tuple[str, str] | None:
    """
    Что видно без нейросети.

    Возвращает («reject», причина) или None, если правила ничего не
    нашли. Одобрять правилами не беремся: отсутствие запрещённых слов
    ещё не значит, что объявление честное.
    """
    text = f"{title or ''}\n{body or ''}"

    found = FORBIDDEN.search(text)
    if found:
        return "reject", f"запрещено к продаже: {found.group(1)}"

    if PREPAY.search(text):
        return "reject", "требует полную предоплату"

    return None


PROMPT = """Ты проверяешь объявления на доске объявлений в Сербии.

Ответь строго JSON: {{"verdict": "ok" | "no" | "?", "why": "..."}}

"ok" — обычное объявление: вещь, услуга, работа, жильё.
"no" — запрещённое законом: оружие, наркотики, рецептурные лекарства,
       поддельные документы, органы, обнал, явное мошенничество,
       интимные услуги.
"?"  — сомневаешься или не хватает данных.

Отклоняй только то, что запрещено законом Сербии. Бывшая в
употреблении вещь — это нормально: косметика, одежда, техника,
детские товары продаются подержанными повсеместно.

Не отклоняй за плохое описание, опечатки, отсутствие цены, странный
заголовок, подержанность или гигиену — это не твоё дело.

Объявление:
{text}"""


def by_model(title: str, body: str) -> tuple[str, str]:
    """
    Что скажет нейросеть.

    Возвращает («ok» | «reject» | «unsure», причина).
    """
    from app.core.ai_title import _ask

    text = f"{title or ''}\n{(body or '')[:600]}"
    answer = _ask(PROMPT.format(text=text), limit=120)

    if not answer:
        # Модель не ответила — это не повод одобрять или отклонять.
        return "unsure", "модель не ответила"

    try:
        data = json.loads(re.sub(r"```\w*|```", "", answer).strip())
    except Exception:                            # noqa: BLE001
        # Модель могла ответить словами вместо разметки. Смотрим на
        # само слово: одного «ok» или «no» довольно, чтобы понять
        # решение, а разбирать её многословие незачем.
        low = answer.lower()
        if re.search(r'"?verdict"?\s*[:=]\s*"?ok', low) or low.strip() == "ok":
            return "ok", "ответ словами"
        if re.search(r'"?verdict"?\s*[:=]\s*"?no', low):
            return "reject", "ответ словами"
        return "unsure", "непонятный ответ модели"

    verdict = str(data.get("verdict", "?"))
    why = str(data.get("why", ""))[:200]

    if verdict == "ok":
        return "ok", why
    if verdict == "no":
        return "reject", why or "модель считает запрещённым"
    return "unsure", why or "модель сомневается"


def check(title: str, body: str) -> tuple[str, str]:
    """
    Проверка объявления целиком.

    Сначала правила — они мгновенны и бесплатны. Что не поймали, идёт
    в модель.
    """
    verdict = by_rules(title, body)
    if verdict:
        return verdict

    return by_model(title, body)
