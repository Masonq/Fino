# Разделы с резюме. У нас это не отдельная категория, а «Работа» с типом
# объявления «Резюме» — и подача у неё другая: не «цена», а желаемая
# зарплата, и человек не продавец.
RESUME_TOPICS = {118482, 98841, 37}


def is_resume(topic_id: int | None) -> bool:
    return topic_id in RESUME_TOPICS


def topic_category(chat_id: int, topic_id: int | None) -> tuple[str | None, bool]:
    """
    Категория по теме и признак «эту тему вообще читаем».

    Второе значение важнее первого: незнакомая тема — это правила, флуд или
    раздел «куплю», и такие сообщения не объявления вовсе.
    """
    chat = CHATS.get(chat_id)
    if not chat or topic_id is None:
        return None, False
    topics = chat["topics"]
    if topic_id not in topics:
        return None, False
    return topics[topic_id], True
