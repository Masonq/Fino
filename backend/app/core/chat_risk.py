"""
Признаки обмана в переписке.

Обманывают в барахолках почти одинаково, и сценариев немного: просят
задаток вперёд «чтобы придержать», зовут в другой мессенджер подальше
от нашей переписки, присылают ссылку на «оплату доставки», торопят
решать прямо сейчас.

Мы не блокируем и не удаляем такие сообщения: ровно те же слова пишет
и честный продавец, которому и правда удобнее в вайбере, а
перестраховка, которая мешает половине людей, хуже редкого обмана.
Поэтому просто показываем получателю строку под сообщением: вот на что
это похоже и почему так делать не стоит.

Проверяем только чужие сообщения и только первое совпадение в
переписке: если предупреждать под каждым, человек перестанет их
читать — а нам нужно, чтобы прочитали хотя бы одно.
"""
import re

# Просьба о предоплате. Главный и самый дорогой для человека случай:
# деньги уходят до того, как он увидел вещь.
_PREPAY = re.compile(
    r"(предоплат\w*|задаток|аванс\w*|капар\w*|kapar\w*|"
    r"перевед\w*\s+(деньги|сумм\w*|сейчас|вперёд|вперед)|"
    r"скинь\w*\s+(деньги|на\s+карт\w*)|"
    r"(оплат\w*|плат\w*)\s+(вперёд|вперед|заранее)|"
    r"unapred\s+(uplat\w*|plat\w*)|"
    r"(картa|карту|карте)\s+сбер\w*|номер\s+карт\w*)",
    re.I)

# Увести из переписки. Сам по себе не обман, но именно так уходят от
# наших проверок и от истории, которую потом можно показать.
_ELSEWHERE = re.compile(
    r"(пиш\w*\s+(в|на)\s+(вайбер|viber|ватсап|вотсап|whatsapp|телеграм\w*|telegram|инстаграм\w*|instagram)|"
    r"мой\s+(вайбер|телеграм\w*|номер)|"
    r"(вайбер|viber|whatsapp|вотсап)\s*[:\-]?\s*\+?\d)",
    re.I)

# Ссылка на «оплату» или «доставку». Почти всегда поддельная страница,
# собирающая данные карты.
_PAYLINK = re.compile(
    r"(https?://\S+|www\.\S+).{0,40}(оплат\w*|доставк\w*|plat\w*|dostav\w*)"
    r"|(оплат\w*|доставк\w*).{0,40}(https?://\S+|www\.\S+)",
    re.I)

# Торопят. Сам по себе признак слабый, поэтому засчитываем только
# вместе с деньгами — иначе предупреждение вылезало бы на каждое
# «заберите сегодня, пожалуйста».
_HURRY = re.compile(
    r"(срочно|прямо\s+сейчас|сейчас\s+же|последний\s+день|успей\w*|hitno|odmah)",
    re.I)


def risk_of(text: str | None) -> str | None:
    """
    На что похоже сообщение: «prepay», «elsewhere», «paylink» или None.

    Возвращаем один признак, а не список: человеку нужно понять, чего
    остеречься, а не прочитать разбор своего собеседника.
    """
    body = (text or "").strip()
    if len(body) < 8:
        return None

    if _PAYLINK.search(body):
        return "paylink"
    if _PREPAY.search(body):
        return "prepay"
    if _ELSEWHERE.search(body):
        return "elsewhere"
    # Торопят и при этом про деньги — считаем как предоплату.
    if _HURRY.search(body) and re.search(r"(деньг\w*|оплат\w*|перевод\w*)", body, re.I):
        return "prepay"
    return None
