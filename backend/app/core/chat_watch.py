"""
Приёмы, которыми обманывают в переписке.

Переписка на любой площадке — главный канал злоупотреблений: там
человека уводят из-под всякого присмотра и там же выманивают деньги.
Мы её никак не смотрели, а жалобы приходят уже после того, как всё
случилось.

Здесь не блокировка и не цензура: сообщение всегда доходит. Мы лишь
помечаем разговор, чтобы он всплыл в служебной очереди — дальше решает
человек.

Что считаем поводом присмотреться:

1. Увод в другой мессенджер до всякого разговора. Само по себе это
   нормально — люди часто договариваются в вотсапе. Но в первом же
   сообщении, вместе с обещанием скидки, это классический приём: увести
   туда, где никто не увидит.

2. Просьба предоплаты, перевода на карту, кода из СМС. Настоящий
   продавец берёт деньги при встрече.

3. Ссылки на оплату и «подтверждение доставки» — на площадке, где
   доставки нет вовсе.

Каждой примете — свой вес. Одна не значит ничего: «переведу вам на
карту» может написать и честный человек. Три подряд — уже картина.
"""
import re

# Другие мессенджеры и просьба перейти.
ELSEWHERE = re.compile(
    r"\b(вотсап|вацап|whats\s?app|вайбер|viber|签|"
    r"напиши(?:те)?\s+(?:мне\s+)?(?:в|на)\s+\w+|"
    r"мой\s+(?:номер|телефон)|звони(?:те)?\s+(?:мне\s+)?на)\b",
    re.IGNORECASE)

# Деньги вперёд.
PREPAY = re.compile(
    r"\b(предоплат\w+|аванс|задаток\s+на\s+карт\w+|"
    r"перевед[иё]те?|переведи\s+на\s+карту|скинь(?:те)?\s+на\s+карту|"
    r"номер\s+карты|реквизит\w+)\b",
    re.IGNORECASE)

# Код из СМС — отдельно от денег: это уже не про оплату, а про угон
# аккаунта, и звучать в переписке о продаже дивана он не должен вовсе.
SMS_CODE = re.compile(
    r"\b(код\s+из\s+смс|смс[- ]?код|одноразов\w+\s+код|код\s+подтверждени\w+)\b",
    re.IGNORECASE)

# Оплата и доставка, которых у нас нет.
FAKE_DELIVERY = re.compile(
    r"\b(оформ\w+\s+доставк\w+|подтверди(?:те)?\s+получени\w+|"
    r"ссылк\w+\s+для\s+оплат\w+|оплати(?:те)?\s+по\s+ссылк\w+|"
    r"безопасн\w+\s+сделк\w+\s+по\s+ссылк\w+)\b",
    re.IGNORECASE)

# Ссылка в сообщении. Сама по себе не улика — люди кидают ссылки на
# похожие товары, — но вместе с просьбой денег это уже другое дело.
LINK = re.compile(r"https?://|t\.me/|\b\w+\.(?:ru|com|net|org|rs|info)\b",
                  re.IGNORECASE)

# Обещание скидки за уход в другое место.
SWEETENER = re.compile(
    r"\b(дешевле|скидк\w+|дам\s+скидку|отдам\s+дешевле)\b", re.IGNORECASE)


def suspicion(text: str, first_message: bool = False) -> tuple[int, list[str]]:
    """
    Возвращает (вес, причины). Вес от 0; тревожным считаем от 3.

    first_message — первое сообщение в переписке. Именно в нём уводы
    опаснее всего: обычный человек сперва спрашивает про вещь.
    """
    text = text or ""
    score = 0
    why = []

    if PREPAY.search(text):
        score += 3
        why.append("просят деньги вперёд")

    if SMS_CODE.search(text):
        score += 3
        why.append("просят код из СМС")

    if FAKE_DELIVERY.search(text):
        score += 3
        why.append("доставка и оплата по ссылке")

    if ELSEWHERE.search(text):
        # В первом сообщении — тревожно, дальше по разговору — обычное
        # дело: договорились и перешли в мессенджер.
        score += 2 if first_message else 1
        why.append("уводят в другой мессенджер")

    if LINK.search(text) and (PREPAY.search(text) or FAKE_DELIVERY.search(text)):
        score += 2
        why.append("ссылка вместе с просьбой денег")

    if SWEETENER.search(text) and ELSEWHERE.search(text):
        score += 2
        why.append("скидка за уход с площадки")

    return score, why


