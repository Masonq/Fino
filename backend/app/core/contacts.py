"""
Контакты в тексте объявления.

Телефон и ник в описании кажутся продавцу удобством, а на деле вредят
ему же: переписка уходит мимо сайта, и с ней уходит всё, что сайт
даёт, — история сделки, отзыв, возможность пожаловаться. Покупателю
хуже тоже: номер в тексте невозможно скрыть, и он остаётся в поиске
Google навсегда.

Поэтому у себя мы просим их убрать, а в перенесённых из чужих чатов
вырезаем сами: там спросить некого.

Ловим то, что в объявлениях пишут живые люди: сербские и российские
номера в любой записи, ники, ссылки на мессенджеры. Телефон,
разбитый словами («38160 два два...»), не ловим — это редкость, и
гоняться за ней значит снова писать правила на каждый случай.
"""
import re

# Номер: плюс с кодом или девять-пятнадцать цифр подряд, допускающие
# пробелы, скобки и дефисы между группами. Короче девяти цифр номеров
# не бывает, и это отделяет их от артикулов и размеров.
PHONE_RE = re.compile(
    r"(?<![\w])(?:\+?\d[\d\s().\-]{8,17}\d)(?![\w])")

# Ник или ссылка на мессенджер. Голую «@» не трогаем: она встречается в
# почтовых адресах и в «M@X».
CONTACT_RE = re.compile(
    r"(@[a-zA-Z][a-zA-Z0-9_]{3,}"
    r"|(?:https?://)?(?:t\.me|telegram\.me|wa\.me|api\.whatsapp\.com|viber\.click)/\S+"
    r"|\b(?:whatsapp|вотсап|ватсап|вайбер|viber|телеграм\w*|telegram)\b\s*[:\-—]?\s*\+?\d[\d\s().\-]{6,})",
    re.I)


def find_contacts(text: str | None) -> list[str]:
    """Что нашли — для сообщения человеку: он должен видеть, о чём речь."""
    body = text or ""
    found = [m.group().strip() for m in PHONE_RE.finditer(body)]
    found += [m.group().strip() for m in CONTACT_RE.finditer(body)]
    # Одно и то же может попасть дважды (ник и ссылка на него).
    seen, out = set(), []
    for item in found:
        key = item.lower()
        if key not in seen:
            seen.add(key)
            out.append(item)
    return out[:5]


def strip_contacts(text: str | None) -> str:
    """
    Вырезает контакты из текста.

    Для перенесённых объявлений: спросить автора мы не можем, а
    оставлять чужой номер в нашей ленте нельзя — по нему пишут мимо
    сайта, и он же остаётся в поиске навсегда.
    """
    body = CONTACT_RE.sub(" ", text or "")
    body = PHONE_RE.sub(" ", body)
    # Строка, где кроме контакта ничего не было, схлопывается в пустую;
    # убираем её целиком, чтобы в описании не зияла дыра.
    # Строка вида «Телефон: (вайбер, воцап)» или «Пишите» — то, что
    # осталось от вырезанного контакта. Смысла в ней нет, убираем
    # целиком. Служебные слова идут цепочкой и вперемешку со скобками,
    # поэтому проверяем так: если в строке не осталось ни одного слова
    # длиннее четырёх букв, кроме служебных, — это был контакт.
    SERVICE = {
        "телефон", "телефоны", "тел", "звонить", "звоните", "пишите",
        "пиши", "контакт", "контакты", "связь", "номер", "whatsapp",
        "вайбер", "viber", "вотсап", "ватсап", "телеграм", "телеграмм",
        "telegram", "воцап", "вацап", "или", "и", "можно", "вотс",
    }
    lines = []
    for line in body.splitlines():
        line = re.sub(r"\s{2,}", " ", line).strip(" ,.;:-—")
        words = [w.strip(" ,.;:()—-\u00ab\u00bb").lower() for w in line.split()]
        meaningful = [w for w in words if w and w not in SERVICE and len(w) > 2]
        if line and not meaningful:
            continue
        lines.append(line)

    kept, blank = [], False
    for line in lines:
        if not line:
            blank = True
            continue
        if kept and blank:
            kept.append("")
        blank = False
        kept.append(line)
    return "\n".join(kept).strip()
