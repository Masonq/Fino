# Кириллица в латиницу — на случай марок, которых нет в словаре выше:
# «Икеа» → «ikea» получается само собой.
_TRANSLIT = str.maketrans({
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "z", "з": "z", "и": "i", "й": "i", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "c", "ч": "c", "ш": "s", "щ": "s", "ъ": "",
    "ы": "i", "ь": "", "э": "e", "ю": "u", "я": "a",
})

_BRAND_MAP: dict[str, set[str]] = {}
for _ru, _en in BRANDS:
    _BRAND_MAP.setdefault(_ru, set()).add(_en)
    _BRAND_MAP.setdefault(_en, set()).add(_ru)


def variants(query: str, limit: int = 4) -> list[str]:
    """
    Во что развернуть запрос, чтобы найти вещь при любом написании.

    Первым идёт то, что набрал человек: по нему совпадения точнее, и в
    выдаче они должны стоять выше.
    """
    text = " ".join(query.split()).strip()
    if not text:
        return []

    out = [text]
    low = text.lower()

    # Марка целиком: «айфон 13» → «iphone 13»
    for name, others in _BRAND_MAP.items():
        if name not in low:
            continue
        for other in others:
            swapped = re.sub(re.escape(name), other, low, flags=re.I)
            if swapped not in out:
                out.append(swapped)

    # Слово кириллицей — пробуем его же латиницей: марок много, всех в
    # словаре не удержать.
    if any("а" <= ch <= "я" or ch == "ё" for ch in low):
        latin = low.translate(_TRANSLIT)
        if latin != low and latin not in out:
            out.append(latin)

    return out[:limit]
