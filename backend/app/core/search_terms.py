"""
Варианты написания запроса: «айфон» и «iPhone» — одно и то же.

В объявлениях марку пишут как придётся: латиницей, кириллицей, с опечатками.
Покупатель набирает так, как привык, и не находит ничего — хотя вещь лежит
в ленте. Для сербской барахолки это обычное дело: половина текстов по-русски,
половина латиницей.

Поэтому запрос разворачиваем в несколько вариантов и ищем по всем сразу.
Словарь марок ведётся вручную — это тот случай, когда список конечен и
известен: марок, которые ищут, десятки, а не тысячи.
"""
