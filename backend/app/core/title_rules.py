def has_object_word(text: str) -> bool:
    """
    Есть ли в строке слово, которым называют предмет.

    Латиница считается названием сразу: марка и модель пишутся ею почти
    всегда, а держать в словаре все бренды мира невозможно.
    """
    if _LATIN_RE.search(text):
        return True
    # Корень должен начинать слово: подстрока где угодно находила «тен» в
    # «толстостенная», и прилагательное сходило за название вещи.
    low = text.lower().replace("ё", "е")
    # «Требуется мойщик» — предмет вакансии назван профессией
    if profession(text):
        return True
    words = re.findall(r"[\w-]+", low)
    for word in words:
        for root in _OBJECT_PREFIXES.get(root_key(word), ()):
            # Корень, записанный с пробелом на конце, — это слово целиком:
            # «топ » не должен ловить «топор» и «топливо».
            if root.endswith(" "):
                if word == root.strip():
                    return True
            elif word.startswith(root):
                return True
    return False


def root_key(word: str) -> str:
    """Первые буквы слова — по ним ищем подходящие корни, а не весь список."""
    return word[:3]


# Корни, разложенные по первым трём буквам: перебирать полтысячи корней для
# каждого слова заголовка слишком дорого, а совпасть может только тот, что
# начинается так же.
_OBJECT_PREFIXES: dict[str, tuple[str, ...]] = {}


# «Скажите, есть ли трансфер до Станишичей? Может кто-то возит?» — это
# вопрос в чат, а не объявление: продавать тут нечего.
_GREETING_LEAD_RE = re.compile(
    r"^(всем\s+)?(привет\w*|здравствуйте|добр(ый|ое|ого)[\s\w]{0,14}|"
    r"zdravo|pozdrav)[\s,!.—-]*", re.I)

_QUESTION_POST_RE = re.compile(
    r"^\s*(скажите|подскажите|посоветуйте|кто.нибудь знает|"
    r"может кто|кто может|ищу кого|есть ли|а есть|нужен совет|"
    r"кто.нибудь\s+(продаёт|продает|отдаёт|отдает|знает|подскажет)|"
    r"ищу\s+(для\s+)?(съ[её]мн|квартиру\s+в\s+аренду)|"
    r"никто не |кто-нибудь |кто нибудь |нет ли |не подскажете|"
    r"вопрос:|помогите найти)", re.I)


def looks_like_question(text: str) -> bool:
    """Сообщение спрашивает, а не предлагает."""
    # Приветствие перед вопросом сдвигает его с начала строки: «Привет!
    # Кто-нибудь продаёт диван?» — тот же вопрос, что и без приветствия.
    head = _GREETING_LEAD_RE.sub("", text.strip())[:200]
    if not _QUESTION_POST_RE.search(head):
        return False
    # Знак вопроса ставят не все: «Может кто-то отдает диван» — та же
    # просьба, что и с ним.
    return True


# Строка существует ради контакта: ник, телефон, «пишите в личку».
_CONTACT_ONLY_RE = re.compile(
    r"^(мой|наш|мои)?\s*(телеграм|телеграмм|telegram|тг|вайбер|viber|"
    r"whatsapp|инстаграм|instagram|номер|тел\.?|контакт\w*)\b|^@\w+", re.I)


def rejects_as_title(text: str, first_line: bool = False) -> bool:
    """
    Строка говорит не о предмете — заголовком быть не может.

    Для первой содержательной строки требование мягче. Словарь предметов
    конечен, а мир вещей — нет: «Каланхоэ», «Антуриум», «Лапушка Софи» в
    нём не значатся, и строгая проверка выбрасывала настоящее название,
    подставляя вместо него случайную строку из середины текста. Чёрные
    списки при этом работают: приветствие, вопрос читателю и контакты не
    станут заголовком и первой строкой.
    """
    line = text.strip()
    if not line:
        return True
    if _CONTACT_ONLY_RE.search(line):
        return True
    # Строка-продолжение: «+ вторая бесплатно», «— и ещё одна». Начинается
    # со знака, а не со слова, и сама по себе ничего не называет.
    if not line[:1].isalnum():
        return True
    # Вопрос — это обращение к читателю, а не название вещи.
    if line.endswith("?"):
        return True
    for pattern in (_SELF_INTRO_RE, _RHETORIC_RE, _DEFINITION_RE,
                    _DETAIL_FIRST_RE, _NO_SUBJECT_VERB_RE):
        if pattern.search(line):
            return True
    # «70 м², 2 комнаты» — обрывок таблицы, а не заголовок. Счётное «4шт
    # бокалы» под правило не подпадает: там за числом идёт товар.
    if _SPEC_FIRST_RE.search(line):
        return True
    # Автор начал объявление с названия — верим ему, даже если слова нет в
    # нашем словаре. Ниже по тексту доверия меньше: там идёт рассказ, и
    # без предметного слова строка почти наверняка не про вещь.
    if first_line:
        # Строка с двоеточием на конце объявляет список — сам предмет
        # назван пунктами ниже: «Продаю пакетом:», «Характеристики:».
        if line.endswith(":"):
            return True
        # Целый абзац вместо названия — это уже рассказ, а не заголовок.
        return len(line.split()) > 20
    return not has_object_word(line)


def strip_trailing_number(text: str) -> str:
    """
    Снимает висящее в конце число без единицы измерения.

    Но не всякое: «Bedside Lamp 2» и «Maxi-Cosi 3 в 1» — это модель, а
    «Два брата-акробата 3» — остаток разметки поста. Отличаем по тому, что
    стоит перед числом: у модели там латиница или другое число.
    """
    match = _TRAILING_NUMBER_RE.search(text)
    if not match:
        return text
    head = text[:match.start()].strip()
    if not head:
        return text
    last = head.split()[-1]
    # «Lamp 2», «Galaxy S21 5», «iPhone 13» — число продолжает название
    if last.isascii() and any(c.isalpha() for c in last):
        return text
    if any(c.isdigit() for c in last):
        return text
    # «размер 37», «объём 2 л», «рост 170» — число относится к слову перед
    # ним и мусором не является: без него теряется сама характеристика.
    if _SPEC_WORD_RE.fullmatch(last):
        return text
    return _TRAILING_NUMBER_RE.sub("", text).strip(" ,.;:—–-")


