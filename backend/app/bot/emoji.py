"""
Премиум-эмодзи в сообщениях бота.

Telegram разрешил их ботам: достаточно подписки Premium у владельца бота,
покупать имя на Fragment больше не нужно.

Каждый значок задаётся парой — номер эмодзи и обычный запасной. Запасной
нужен всегда: он показывается там, где премиум-эмодзи отрисовать нельзя —
в уведомлениях, у пересланных сообщений, в старых приложениях. Без него
человек увидит пустое место.

Номера берутся так: отправьте нужный значок боту @idstickerbot или
посмотрите в наборе через @Stickers. Пока номера не заданы, всё работает
на обычных эмодзи — ничего не ломается.
"""

# Номер премиум-эмодзи → обычный запасной.
#
# Пусто до тех пор, пока не выбраны значки: пустая запись означает
# «показывай обычный», и сообщения выглядят как раньше.
EMOJI: dict[str, tuple[str, str | None]] = {
    # ключ: (обычный значок, номер премиум-эмодзи)
    "publish": ("⬆️", "6030861234432121355"),
    "topic": ("🗂", "5818955300463447293"),
    "edit": ("🏷", "5854776233950188167"),
    "money": ("💵", "5974217466270716579"),
    "cancel": ("🙈", "5952055319059239589"),      # перечёркнутый глаз
    "back": ("⬅️", "5877536313623711363"),
    "open": ("➡️", "5877468380125990242"),
    "sold": ("🔨", "6028226658543082010"),        # молоток — продано
    "listings": ("📄", "5956561916573782596"),
    "done": ("❌", "5985346521103604145"),        # «ПРОДАНО» в посте
    "live": ("🟢", None),
}

# Цифры для списка объявлений: вместо «✅ 1» на кнопке настоящая цифра.
DIGITS: dict[int, tuple[str, str]] = {
    1: ("1\ufe0f\u20e3", "5794182096603847292"),
    2: ("2\ufe0f\u20e3", "5794303034292968945"),
    3: ("3\ufe0f\u20e3", "5794031944547178894"),
    4: ("4\ufe0f\u20e3", "5793901252987330401"),
    5: ("5\ufe0f\u20e3", "5794066823976592976"),
    6: ("6\ufe0f\u20e3", "5794235255414069703"),
    7: ("7\ufe0f\u20e3", "5794030595927448202"),
    8: ("8\ufe0f\u20e3", "5794426162415409242"),
    9: ("9\ufe0f\u20e3", "5793905801357695657"),
}


def digit(number: int) -> str:
    """
    Значок цифры для списка.

    Больше девяти объявлений в списке не помещается, да и не нужно —
    дальше идёт обычная цифра.
    """
    plain, custom_id = DIGITS.get(number, (str(number), ""))
    if not custom_id:
        return plain
    return f'<tg-emoji emoji-id="{custom_id}">{plain}</tg-emoji>'


def emoji(key: str) -> str:
    """
    Значок для сообщения.

    Если номер премиум-эмодзи задан, оборачиваем обычный значок в разметку
    — Telegram покажет премиум тем, кто его видит, и обычный остальным.
    Одна и та же строка работает для всех, отдельной ветки не нужно.
    """
    plain, custom_id = EMOJI.get(key, ("", None))
    if not plain:
        return ""
    if not custom_id:
        return plain
    return f'<tg-emoji emoji-id="{custom_id}">{plain}</tg-emoji>'


def set_custom(key: str, custom_id: str) -> None:
    """Задаёт номер премиум-эмодзи для значка."""
    plain, _ = EMOJI.get(key, ("❓", None))
    EMOJI[key] = (plain, custom_id)


def icon(key: str) -> str | None:
    """
    Номер значка для кнопки.

    У кнопок своё поле под премиум-эмодзи: разметка в подписи не
    работает, значок задаётся отдельно. Нет номера — нет и значка,
    подпись останется обычной.
    """
    _, custom_id = EMOJI.get(key, ("", None))
    return custom_id


def digit_icon(number: int) -> str | None:
    """Номер значка-цифры для кнопки списка."""
    _, custom_id = DIGITS.get(number, ("", ""))
    return custom_id or None
