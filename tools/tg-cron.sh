#!/usr/bin/env bash
# Регулярный перенос объявлений из телеграм-чатов.
#
# Ставится в расписание одной строкой (см. ниже). Два действия подряд:
# сначала забираем новое, потом проверяем, не продано ли уже перенесённое.
#
# Запуски не должны накладываться: заход длится минуты, а при большом
# объёме и дольше — flock отсекает второй запуск, пока идёт первый.
#
#   crontab -e
#   7 * * * * /usr/bin/flock -n /tmp/plonk-tg.lock /opt/fino/tools/tg-cron.sh >> /var/log/plonk-tg.log 2>&1
set -u

cd /opt/fino/backend || exit 1
source venv/bin/activate

echo "=== $(date '+%Y-%m-%d %H:%M') ==="

# Читаем только то, что появилось после прошлого захода. Чаты живые —
# по три-четыре тысячи сообщений в сутки, — и заход по дате каждый час
# перечитывал бы тысячи уже разобранных сообщений.
#
# Ограничение по дате остаётся страховкой: если переносить ещё нечего
# (первый запуск, пустая база), не вычитываем весь архив.
python3 -m app.core.tg_import --since-last --days 3

# Раз в сутки, ночью, проверяем перенесённое: не продали ли вещь и не
# устарело ли объявление. Чаще незачем — это лишние обращения к Telegram.
if [ "$(date +%H)" = "04" ]; then
    python3 -m app.core.tg_refresh --days 45
fi
