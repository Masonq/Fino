#!/usr/bin/env bash
# Ночная учёба классификатора: размечаем, переобучаем, применяем.
#
# Днём лимиты нейросети тратит разбор заголовков, ночью в ленте затишье —
# самое время учить модель. Три шага подряд, каждый следующий имеет смысл
# только после предыдущего.
#
# Ставится в расписание одной строкой:
#
#   crontab -e
#   30 3 * * * /usr/bin/flock -n /tmp/plonk-learn.lock /opt/fino/tools/learn-cron.sh >> /var/log/plonk-learn.log 2>&1
#
# Половина четвёртого — час после смены суток по тихоокеанскому времени,
# когда у Gemini обновляется дневная квота.
set -u

cd /opt/fino/backend || exit 1
source venv/bin/activate

echo "=== $(date '+%Y-%m-%d %H:%M') ==="

# Полторы тысячи за ночь: столько дают четыре бесплатных тарифа вместе,
# и это укладывается в паузу между запросами, которую держит сам код.
# Уже размеченное не переспрашивается, набор только растёт.
python ../tools/label-with-ai.py --limit 1500

# Переобучаем на всём накопленном. Доверие считается по каждому разделу
# отдельно, поэтому новые примеры добавляют разделы по одному, а не
# улучшают всё разом.
python ../tools/train-categories.py --labels

# Подкатегории — тот же приём, только уровнем ниже и отдельной моделью
# на каждого родителя (см. category_model.py, SUB_MIN_SAMPLES): словари
# разных родителей не пересекаются, нет смысла путать их в одной сумке.
# Заводим по мере того, как у родителя набирается 15+ примеров на
# КАЖДУЮ его подкатегорию — на конец августа 2026 это только
# electronics, остальные добавятся сюда по мере накопления данных.
for parent in electronics; do
    python ../tools/label-subcategories-with-ai.py "$parent" --limit 200
    python ../tools/train-subcategories.py "$parent"
done

# Применяем к уже перенесённым объявлениям: раз модель стала лучше,
# часть из них лежит не в своём разделе. classify_sub() сама проверяет
# обученную модель подкатегории первым делом, так что свежая модель
# выше подхватывается тут же, без отдельного шага.
python ../tools/tg-reimport.py --apply

# Догоняем перевод: публичные переводчики отвечают через раз, и часть
# объявлений остаётся одноязычной. Двести за ночь — по силам лимитам.
python ../tools/translate-missing.py --limit 200

# Заодно убираем снимки, оставшиеся от отсеянных объявлений.
python ../tools/clean-media.py --apply

echo "=== готово $(date '+%H:%M') ==="
